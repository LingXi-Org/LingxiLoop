import { test } from '@e2e-dev/web'
import { expect, type TestFixtures } from 'e2e'

async function chooseTeacher(screen: TestFixtures['screen']) {
  await screen.getByLabel('搜索公司教师', { exact: true }).fill('合成新')
  await screen.getByRole('combobox', '公司教师', { exact: true }).tap()
  await expect(screen.getByRole('option', /合成学生/)).toHaveCount(0)
  await screen.getByRole('option', /合成新教师/).tap()
}

test('course administrator explicitly adds one company teacher and persists the readback', async ({ app, browser, screen }) => {
  await app.open('/e2e/course-teacher/index.html?scenario=course')
  await expect(screen.getByText('组织教师身份不会自动加入课程。', { exact: true })).toBeVisible()
  await screen.getByRole('button', '添加课程教师', { exact: true }).tap()
  await chooseTeacher(screen)
  await screen.getByRole('button', '确认加入本课程', { exact: true }).tap()
  await expect(screen.getByRole('dialog')).toHaveCount(0)
  await expect(screen.getByRole('row').filter({ hasText: '合成新教师' })).toContainText('课程管理者')
  const evidence = JSON.parse((await screen.getByLabel('授权证据').textContent())!)
  expect(evidence.puts.length).toBe(1)
  expect(evidence.puts[0].path).toBe('/api/courses/course-a/members/new-teacher')
  expect(evidence.puts[0].body.role).toBe('TEACHER')
  await browser.reload()
  await expect(screen.getByRole('row').filter({ hasText: '合成新教师' })).toContainText('课程管理者')
  await app.screenshot('course-teacher-readback')
})

