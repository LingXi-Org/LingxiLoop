import { test } from '@e2e-dev/web'
import { expect } from 'e2e'

// Failure cases: one row per text part; mobile misses the actions; false copy
// success; both ratings selected; duplicate regenerate sends; menu loses focus.
for (const width of [1440, 390]) {
  test(`complete assistant actions copy, rate, regenerate and export (${width})`, async ({ app, browser, screen }) => {
    await browser.setViewport({ width, height: 960 })
    await app.open('/scripts/ui-experience-browser-check.html?surface=主应用&capture=1&theme=light&scenario=message-actions')
    if (width < 768) await browser.locator('[data-slot="sidebar"] [role="button"]').first().tap()
    const actions = browser.locator('[data-slot="message-actions"]')
    await expect(actions).toHaveCount(1)
    await expect(actions).toBeVisible()
    await expect(browser.locator('[data-slot="message-actions"] > button')).toHaveCount(5)
    await browser.evaluate(() => {
      Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async (text: string) => {
        if (document.documentElement.dataset.copyDenied) throw new Error('clipboard denied')
        document.documentElement.dataset.copiedReply = text
      } } })
      return null
    })
    await screen.getByRole('button', '复制回复').tap()
    await expect(screen.getByRole('button', '已复制回复')).toBeVisible()
    expect(await browser.evaluate(() => document.documentElement.dataset.copiedReply ?? null)).toBe('第一段回复。\n最后一段回复。')
    await expect(screen.getByRole('button', '复制回复')).toBeVisible()
    await browser.evaluate(() => { document.documentElement.dataset.copyDenied = 'true'; return null })
    await screen.getByRole('button', '复制回复').tap()
    await expect(screen.getByRole('button', '已复制回复')).toHaveCount(0)
    await screen.getByRole('button', '评价为有帮助').tap()
    await expect(screen.getByRole('button', '评价为有帮助')).toHaveAttribute('aria-pressed', 'true')
    await screen.getByRole('button', '评价为无帮助').tap()
    await expect(screen.getByRole('button', '评价为有帮助')).toHaveAttribute('aria-pressed', 'false')
    await expect(screen.getByRole('button', '评价为无帮助')).toHaveAttribute('aria-pressed', 'true')
    await screen.getByRole('button', '评价为无帮助').tap()
    await expect(screen.getByRole('button', '评价为无帮助')).toHaveAttribute('aria-pressed', 'false')
    await app.screenshot(`message-actions-complete-${width}`)
    await screen.getByRole('button', '更多回复操作').tap()
    await expect(screen.getByRole('menuitem', '回复')).toBeVisible()
    const download = await browser.waitForDownload(() => screen.getByRole('menuitem', '导出为 Markdown').tap())
    expect(download.suggestedFilename).toMatch(/^message-\d+\.md$/)
    await expect(screen.getByRole('button', '更多回复操作')).toBeFocused()
    await screen.getByRole('button', '更多回复操作').tap()
    await screen.getByRole('menuitem', '回复').tap()
    await expect(screen.getByRole('button', '取消回复')).toBeVisible()
    await expect(browser.locator('[data-chat-composer-bar]')).toContainText('第一段回复。')
    await screen.getByRole('button', '重新生成回复').tap()
    await expect(browser.locator('[data-slot="message-actions"] svg.lucide-refresh-cw')).toHaveAttribute('class', /animate-spin/)
    expect(await browser.evaluate(() => JSON.parse(document.documentElement.dataset.regeneratePayload!))).toMatchObject({
      role: 'user', content: [{ type: 'text', text: '请重新生成这条回复。' }],
      metadata: { custom: { mentionedIds: ['scout'], replyToClientMsgNo: 'actions-reply', regenerateOfClientMsgNo: 'actions-reply' } },
    })
    await app.screenshot(`message-actions-regenerating-${width}`)
    await browser.evaluate(() => window.dispatchEvent(new CustomEvent('message-actions-step', { detail: 'sent' })))
    await expect(browser.locator('[data-slot="message-actions"] svg.lucide-refresh-cw')).not.toHaveAttribute('class', /animate-spin/)
    await expect(screen.getByText('请重新生成这条回复。', { exact: true })).toHaveCount(0)
    const input = browser.locator('[contenteditable="true"]')
    await input.tap()
    await browser.keyboard.type('保留分支草稿')
    await browser.evaluate(() => window.dispatchEvent(new CustomEvent('message-actions-step', { detail: 'branch-start' })))
    const branches = browser.locator('[data-slot="message-branches"]')
    await expect(branches).toContainText('2 / 2')
    await screen.getByRole('button', '上一版回复').tap()
    await expect(branches).toContainText('1 / 2')
    await expect(browser.locator('[data-msg-id="actions-reply"] [data-agent-body]').first()).toContainText('第一段回复。')
    await browser.evaluate(() => window.dispatchEvent(new CustomEvent('message-actions-step', { detail: 'branch-complete' })))
    await expect(branches).toContainText('1 / 2')
    await expect(input).toContainText('保留分支草稿')
    await screen.getByRole('button', '下一版回复').tap()
    await expect(branches).toContainText('2 / 2')
    await expect(browser.locator('[data-msg-id="branch-1"] [data-agent-body]')).toContainText('重新生成的第 2 版回复。')
    await browser.evaluate(() => { delete document.documentElement.dataset.copyDenied; return null })
    await screen.getByRole('button', '复制回复').tap()
    expect(await browser.evaluate(() => document.documentElement.dataset.copiedReply ?? null)).toBe('重新生成的第 2 版回复。')
    await browser.evaluate(() => window.dispatchEvent(new CustomEvent('message-actions-step', { detail: 'followup' })))
    await screen.getByRole('button', '上一版回复').tap()
    await screen.getByRole('button', '重新生成回复').tap()
    await browser.evaluate(() => window.dispatchEvent(new CustomEvent('message-actions-step', { detail: 'sent' })))
    await browser.evaluate(() => window.dispatchEvent(new CustomEvent('message-actions-step', { detail: 'branch-start' })))
    await browser.evaluate(() => window.dispatchEvent(new CustomEvent('message-actions-step', { detail: 'branch-complete' })))
    await expect(branches).toContainText('3 / 3')
    await screen.getByRole('button', '下一版回复').tap()
    await expect(branches).toContainText('1 / 3')
    await expect(screen.getByText('后续消息仍在原处。', { exact: true })).toBeVisible()
    await expect.poll(() => browser.evaluate(() => getComputedStyle(document.querySelector('[data-msg-id="actions-reply"]')!).opacity)).toBe('1')
    await app.screenshot(`message-branches-${width}`)
    await app.open('/scripts/ui-experience-browser-check.html?surface=主应用&capture=1&theme=light&scenario=message-actions&branched=1')
    if (width < 768) await browser.locator('[data-slot="sidebar"] [role="button"]').first().tap()
    await expect(branches).toContainText('3 / 3')
    await expect(browser.locator('[data-slot="message-actions"]')).toHaveCount(1)
    await browser.evaluate(() => window.dispatchEvent(new CustomEvent('message-actions-step', { detail: 'read-only' })))
    await expect(screen.getByRole('button', '评价为有帮助')).toBeDisabled()
    await expect(screen.getByRole('button', '重新生成回复')).toBeDisabled()
    await app.screenshot(`message-actions-read-only-${width}`)
    await browser.evaluate(() => window.dispatchEvent(new CustomEvent('message-actions-step', { detail: 'branch-failed' })))
    await expect(branches).toContainText('4 / 4')
    await screen.getByRole('button', '重试', { exact: true }).tap()
    expect(await browser.evaluate(() => JSON.parse(document.documentElement.dataset.regeneratePayload!))).toMatchObject({
      metadata: { custom: { regenerateOfClientMsgNo: 'actions-reply', replyToClientMsgNo: 'actions-reply' } },
    })
    await browser.evaluate(() => window.dispatchEvent(new CustomEvent('message-actions-step', { detail: 'sent' })))
    await expect(browser.locator('[data-slot="error-state"][role="alert"]')).toBeVisible()
    await browser.evaluate(() => window.dispatchEvent(new CustomEvent('message-actions-step', { detail: 'failed' })))
    const error = browser.locator('[data-slot="error-state"][role="alert"]')
    await expect(error).toContainText('回复生成失败')
    await expect(error).toContainText('超时')
    await expect(screen.getByRole('button', '重试', { exact: true })).toBeEnabled()
    await expect.poll(() => browser.evaluate(() => ({
      message: getComputedStyle(document.querySelector('[data-msg-id="actions-reply"]')!).opacity,
      error: getComputedStyle(document.querySelector('[data-slot="error-state"]')!).opacity,
    }))).toEqual({ message: '1', error: '1' })
    await app.screenshot(`message-error-retry-${width}`)
    await screen.getByRole('button', '重试', { exact: true }).tap()
    await expect(browser.locator('[data-slot="error-state"][role="status"]')).toContainText('正在重试')
    await expect(browser.locator('[data-msg-id="actions-reply"]')).toContainText('最后一段回复。')
    expect(await browser.evaluate(() => JSON.parse(document.documentElement.dataset.regeneratePayload!))).toMatchObject({
      role: 'user', content: [{ type: 'text', text: '请重试这条消息。' }],
      metadata: { custom: { mentionedIds: ['scout'], replyToClientMsgNo: 'actions-question' } },
    })
    await app.screenshot(`message-error-retrying-${width}`)
    await browser.evaluate(() => window.dispatchEvent(new CustomEvent('message-actions-step', { detail: 'send-failed' })))
    await expect(error).toBeVisible()
    await expect(screen.getByRole('button', '重试', { exact: true })).toBeEnabled()
    expect(await browser.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
