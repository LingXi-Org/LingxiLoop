import { mkdir, writeFile } from 'node:fs/promises'
import { test } from '@e2e-dev/web'
import { expect } from 'e2e'

const original = '# 旧卡片\n\n需要一起保留的内容。'
const evidenceDirectory = 'artifacts/canvas-app/review-races/green'
async function evidence(name: string, data: unknown) {
  await mkdir(evidenceDirectory, { recursive: true })
  await writeFile(`${evidenceDirectory}/${name}.json`, JSON.stringify(data, null, 2))
}

test('save notifications retain an undo to the former baseline and the next save uses the acknowledged revision', async ({ app, browser }) => {
  await app.open('/e2e/canvas-app/index.html')
  await browser.locator('[data-canvas-frame="fixture-frame"] .canvas-frame-body').tap()
  const editor = browser.frameLocator('iframe[data-canvas-document-app]')
  const field = editor.getByLabel('编辑文档')
  await expect(field).toHaveValue(original)
  await browser.evaluate(async () => { await fetch('/__canvas/failure', { method: 'POST', body: JSON.stringify({ delay: 1200 }) }); return true })
  await field.fill('已经提交但尚未确认的修改')
  await editor.getByRole('button', '保存修改', { exact: true }).press('Enter')
  await expect.poll(() => browser.evaluate(async () => (await fetch('/__canvas/evidence').then(r => r.json())).patches.length)).toBe(1)
  await field.fill(original)
  await expect(editor.getByRole('status')).toHaveText('上次修改已保存；当前修改尚未保存。')
  await expect(field).toHaveValue(original)
  await expect(editor.getByRole('button', '保存修改', { exact: true })).toBeEnabled()
  await app.screenshot('save-undo-preserved')
  await editor.getByRole('button', '保存修改', { exact: true }).press('Enter')
  await expect(editor.getByRole('status')).toHaveText('已保存 · 第 3 版')
  const result = await browser.evaluate(async () => fetch('/__canvas/evidence').then(r => r.json()))
  expect(result.patches.map((patch: { baseRevision: number }) => patch.baseRevision)).toEqual([1, 2])
  expect(result.document.content).toBe(original)
  expect(result.feedback.length).toBe(0)
  await evidence('save-undo', { expectedDraft: original, result })
})

test('multiple edits during a pending save preserve the latest draft', async ({ app, browser }) => {
  await app.open('/e2e/canvas-app/index.html')
  await browser.locator('[data-canvas-frame="fixture-frame"] .canvas-frame-body').tap()
  const editor = browser.frameLocator('iframe[data-canvas-document-app]')
  const field = editor.getByLabel('编辑文档')
  await expect(field).toHaveValue(original)
  await browser.evaluate(async () => { await fetch('/__canvas/failure', { method: 'POST', body: JSON.stringify({ delay: 1500 }) }); return true })
  await field.fill('第一批提交')
  await editor.getByRole('button', '保存修改', { exact: true }).press('Enter')
  await expect.poll(() => browser.evaluate(async () => (await fetch('/__canvas/evidence').then(r => r.json())).patches.length)).toBe(1)
  await field.fill('第二次输入')
  await field.fill(original)
  await field.fill('第三次输入仍需保留')
  await expect(editor.getByRole('status')).toHaveText('上次修改已保存；当前修改尚未保存。')
  await expect(field).toHaveValue('第三次输入仍需保留')
  await editor.getByRole('button', '保存修改', { exact: true }).press('Enter')
  await expect(editor.getByRole('status')).toHaveText('已保存 · 第 3 版')
  const result = await browser.evaluate(async () => fetch('/__canvas/evidence').then(r => r.json()))
  expect(result.patches.map((patch: { baseRevision: number }) => patch.baseRevision)).toEqual([1, 2])
  expect(result.document.content).toBe('第三次输入仍需保留')
  expect(result.feedback.length).toBe(0)
  await evidence('save-multiple-edits', result)
})

for (const [label, nextDraft] of [['new-text', '确认以后新写的草稿'], ['undo-to-old-baseline', original]]) test(`typing after reload confirmation retains the original CAS baseline: ${label}`, async ({ app, browser, screen }) => {
  await app.open('/e2e/canvas-app/index.html')
  await browser.locator('[data-canvas-frame="fixture-frame"] .canvas-frame-body').tap()
  const editor = browser.frameLocator('iframe[data-canvas-document-app]')
  const field = editor.getByLabel('编辑文档')
  await expect(field).toBeEnabled()
  await field.fill('确认放弃的旧草稿')
  await screen.getByRole('button', 'Fixture remote edit', { exact: true }).tap()
  await expect(editor.getByRole('status')).toContainText('草稿已保留')
  await browser.evaluate(async () => { await fetch('/__canvas/failure', { method: 'POST', body: JSON.stringify({ readDelay: 1200 }) }); return true })
  await editor.getByRole('button', '重新载入已保存版本', { exact: true }).press('Enter')
  await screen.getByRole('alertdialog').getByRole('button', '重新载入', { exact: true }).tap()
  await field.fill(nextDraft)
  await expect(editor.getByRole('status')).toHaveText('读取期间有新修改；草稿已保留，请核对后重新载入。')
  await expect(field).toHaveValue(nextDraft)
  await app.screenshot(`reload-${label}-preserved`)
  // Preserving text must not silently adopt an unseen remote baseline.
  await editor.getByRole('button', '保存修改', { exact: true }).press('Enter')
  await expect(editor.getByRole('status')).toContainText('文档已有新版本')
  await expect(field).toHaveValue(nextDraft)
  const result = await browser.evaluate(async () => fetch('/__canvas/evidence').then(r => r.json()))
  expect(result.patches[0].baseRevision).toBe(1)
  expect(result.document.revision).toBe(2)
  expect(result.document.content).toBe('远端已保存的新版本')
  expect(result.feedback.length).toBe(0)
  await editor.getByRole('button', '重新载入已保存版本', { exact: true }).press('Enter')
  await screen.getByRole('alertdialog').getByRole('button', '重新载入', { exact: true }).tap()
  await expect(field).toHaveValue('远端已保存的新版本')
  await expect(editor.getByRole('status')).toHaveText('已保存 · 第 2 版')
  await evidence(`reload-${label}`, { expectedDraft: nextDraft, result })
})
