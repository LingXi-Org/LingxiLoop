import { mkdir, writeFile } from 'node:fs/promises'
import { test } from '@e2e-dev/web'
import { expect } from 'e2e'
const original = '# 旧卡片\n\n需要一起保留的内容。'
const output = 'artifacts/canvas-app/review-failures/green'
async function record(name: string, result: unknown) {
  await mkdir(output, { recursive: true })
  await writeFile(`${output}/${name}.json`, JSON.stringify(result, null, 2))
}

test('save conflict readback retains undo and leave protection after failure', async ({ app, browser, screen }) => {
  await app.open('/e2e/canvas-app/index.html')
  await browser.locator('[data-canvas-frame="fixture-frame"] .canvas-frame-body').tap()
  const editor = browser.frameLocator('iframe[data-canvas-document-app]')
  const field = editor.getByLabel('编辑文档')
  await expect(field).toHaveValue(original)
  await field.fill('已发出的本地草稿 A')
  await screen.getByRole('button', 'Fixture remote edit', { exact: true }).tap()
  await expect(editor.getByRole('status')).toContainText('草稿已保留')
  await browser.evaluate(async () => { await fetch('/__canvas/failure', { method: 'POST', body: JSON.stringify({ readDelay: 1200 }) }); return true })
  await editor.getByRole('button', '保存修改', { exact: true }).press('Enter')
  await expect.poll(() => browser.evaluate(async () => (await fetch('/__canvas/evidence').then(r => r.json())).patches.length)).toBe(1)
  await field.fill(original)
  await expect(editor.getByRole('status')).toHaveText('文档已有新版本；你的草稿已保留，请核对后重新载入。')
  await expect(editor.getByRole('button', '保存修改', { exact: true })).toBeEnabled()
  await expect(field).toHaveValue(original)
  await screen.getByRole('button', '返回对话', { exact: true }).tap()
  await expect(screen.getByRole('alertdialog')).toBeVisible()
  await screen.getByRole('alertdialog').getByRole('button', '取消', { exact: true }).tap()
  await expect(field).toHaveValue(original)
  await app.screenshot('failed-save-undo-retained')
  await editor.getByRole('button', '保存修改', { exact: true }).press('Enter')
  await expect.poll(() => browser.evaluate(async () => (await fetch('/__canvas/evidence').then(r => r.json())).patches.length)).toBe(2)
  await expect(editor.getByRole('button', '保存修改', { exact: true })).toBeEnabled()
  const result = await browser.evaluate(async () => fetch('/__canvas/evidence').then(r => r.json()))
  expect(result.patches.map((patch: { baseRevision: number }) => patch.baseRevision)).toEqual([1, 1])
  expect(result.document.content).toBe('远端已保存的新版本')
  expect(result.document.revision).toBe(2)
  expect(result.feedback.length).toBe(0)
  await record('save-conflict-undo', result)
})

for (const mode of ['http-failure', 'sdk-cancellation']) test(`reload ${mode} retains input generation and the original CAS baseline`, async ({ app, browser, screen }) => {
  await app.open('/e2e/canvas-app/index.html')
  await browser.locator('[data-canvas-frame="fixture-frame"] .canvas-frame-body').tap()
  const editor = browser.frameLocator('iframe[data-canvas-document-app]')
  const field = editor.getByLabel('编辑文档')
  await expect(field).toHaveValue(original)
  await field.fill('准备重载的旧草稿 A')
  await screen.getByRole('button', 'Fixture remote edit', { exact: true }).tap()
  await expect(editor.getByRole('status')).toContainText('草稿已保留')
  await browser.evaluate(async (kind) => { await fetch('/__canvas/failure', { method: 'POST', body: JSON.stringify({ readDelay: 1500, readFailures: kind === 'http-failure' ? 1 : 0 }) }); return true }, mode)
  if (mode === 'sdk-cancellation') await browser.evaluate(() => { document.querySelector<HTMLIFrameElement>('iframe[data-canvas-document-app]')!.contentWindow!.postMessage({ fixtureCancelNextDocumentRead: true }, '*'); return true })
  await editor.getByRole('button', '重新载入已保存版本', { exact: true }).press('Enter')
  await screen.getByRole('alertdialog').getByRole('button', '重新载入', { exact: true }).tap()
  await field.fill(original)
  if (mode === 'sdk-cancellation') {
    await editor.getByRole('button', 'Fixture cancel document request', { exact: true }).press('Enter')
    await expect(editor.getByLabel('Fixture cancelled document requests')).toHaveText('1')
  } else await expect.poll(() => browser.evaluate(async () => (await fetch('/__canvas/evidence').then(r => r.json())).failedReads)).toBe(1)
  await expect(editor.getByRole('button', '保存修改', { exact: true })).toBeEnabled()
  await expect(field).toHaveValue(original)
  await screen.getByRole('button', '返回对话', { exact: true }).tap()
  await expect(screen.getByRole('alertdialog')).toBeVisible()
  await screen.getByRole('alertdialog').getByRole('button', '取消', { exact: true }).tap()
  await expect(field).toHaveValue(original)
  await app.screenshot(`reload-${mode}-undo-retained`)
  await browser.evaluate(async () => { await fetch('/__canvas/failure', { method: 'POST', body: JSON.stringify({ readDelay: 0, readFailures: 0 }) }); return true })
  await editor.getByRole('button', '保存修改', { exact: true }).press('Enter')
  await expect(editor.getByRole('status')).toHaveText('文档已有新版本；你的草稿已保留，请核对后重新载入。')
  const result = await browser.evaluate(async () => fetch('/__canvas/evidence').then(r => r.json()))
  expect(result.patches[0].baseRevision).toBe(1)
  expect(result.document.content).toBe('远端已保存的新版本')
  expect(result.document.revision).toBe(2)
  expect(result.feedback.length).toBe(0)
  await record(mode, result)
})
