test('same-source SDK requests reject undeclared capabilities and honor request cancellation', async ({ app, browser }) => {
  await app.open('/e2e/canvas-app/index.html')
  await browser.locator('[data-canvas-frame="fixture-frame"] .canvas-frame-body').tap()
  const editor = browser.frameLocator('iframe[data-canvas-document-app]')
  await expect(editor.getByLabel('编辑文档')).toBeEnabled()
  await browser.evaluate(async () => { await fetch('/__canvas/failure', { method: 'POST', body: JSON.stringify({ delay: 800 }) }); return true })
  await browser.evaluate(() => { document.querySelector<HTMLIFrameElement>('iframe[data-canvas-document-app]')!.contentWindow!.postMessage({ fixtureProtocolProbe: true }, '*'); return true })
  await editor.getByRole('button', 'Fixture protocol probe', { exact: true }).press('Enter')
  await expect(editor.getByLabel('Fixture protocol evidence')).toBeVisible()
  const result = JSON.parse(await editor.getByLabel('Fixture protocol evidence').textContent() ?? '{}')
  expect(result.rejected.every((entry: { rejected: boolean }) => entry.rejected)).toBe(true)
  expect(result.rejected.length).toBe(6)
  expect(result.capabilities.message).toBe(undefined)
  expect(result.capabilities.serverResources).toBe(undefined)
  expect(result.cancelled).toBe(true)
  await expect.poll(() => browser.evaluate(async () => (await fetch('/__canvas/evidence').then(r => r.json())).finishedPatches)).toBe(1)
  const evidence = await browser.evaluate(async () => await fetch('/__canvas/evidence').then(r => r.json()))
  expect(evidence.patches.length).toBe(1)
  expect(evidence.feedback.length).toBe(0)
  // Cancellation is not rollback: the delayed request may already be committed.
  await expect(editor.getByLabel('编辑文档')).toHaveValue('# 旧卡片\n\n需要一起保留的内容。')
  await writeFile('artifacts/canvas-app/capabilities-cancel.json', JSON.stringify({ ...evidence, protocol: result }, null, 2))
})
