import { mkdir, writeFile } from 'node:fs/promises'
import { test } from '@e2e-dev/web'
import { expect } from 'e2e'

test('official SDK edits a legacy document, retains one live page and stages explicit feedback', async ({ app, browser, screen }) => {
  await browser.addInitScript(() => {
    const methods: string[] = []
    Object.assign(window, { canvasAppMethods: methods })
    window.addEventListener('message', event => { if (event.data?.method) methods.push(event.data.method) })
  })
  await app.open('/e2e/canvas-app/index.html')
  await expect(browser.frameLocator('iframe[title="旧网页卡片"]').getByText('旧网页内容', { exact: true })).toBeVisible()
  await expect(browser.locator('iframe[title="旧网页卡片"]')).toHaveAttribute('sandbox', '')
  await browser.locator('[data-canvas-frame="fixture-frame"] .canvas-frame-body').tap()
  const editor = browser.frameLocator('iframe[data-canvas-document-app]')
  await expect(browser.locator('[data-canvas-app-phase]')).toHaveAttribute('data-canvas-app-phase', 'ready')
  await expect(editor.getByLabel('编辑文档')).toHaveValue('# 旧卡片\n\n需要一起保留的内容。')
  await editor.getByLabel('编辑文档').fill('用户保存的修改与选区')
  // Native pointer coordinates in the transformed iframe; the engine's locator
  // tap currently applies the canvas scale twice. Other App actions test keyboard.
  const point = await browser.evaluate(() => { const rect = document.querySelector('iframe[data-canvas-document-app]')!.getBoundingClientRect(); return { x: rect.left + 40, y: rect.bottom - 25 } })
  await browser.mouse.move(point.x, point.y)
  await browser.mouse.down()
  await browser.mouse.up()
  await expect(editor.getByRole('status')).toHaveText('已保存 · 第 2 版')
  await browser.evaluate(() => { Object.assign(window, { retainedCanvasFrame: document.querySelector('iframe[data-canvas-document-app]') }); return true })
  for (let i = 0; i < 10; i++) {
    await screen.getByRole('button', '预览', { exact: true }).tap()
    await screen.getByRole('button', '继续编辑', { exact: true }).tap()
  }
  expect(await browser.evaluate(() => (window as unknown as { retainedCanvasFrame: Element }).retainedCanvasFrame === document.querySelector('iframe[data-canvas-document-app]'))).toBe(true)
  await expect(editor.getByLabel('编辑文档')).toHaveValue('用户保存的修改与选区')
  const methods = await browser.evaluate(() => (window as unknown as { canvasAppMethods: string[] }).canvasAppMethods)
  expect(methods.filter(method => method === 'ui/initialize').length).toBe(1)
  await editor.getByRole('button', '引用选区', { exact: true }).press('Enter')
  await expect(screen.getByLabel('待发送的画布引用')).toContainText('用户保存的修改与选区')
  await app.screenshot('canvas-mcp-app-reference-preview')
  await screen.getByRole('button', '取消', { exact: true }).tap()
  const cancelled = await browser.evaluate(async () => await fetch('/__canvas/evidence').then(r => r.json()))
  expect(cancelled.feedback.length).toBe(0)
  expect(cancelled.comments.length).toBe(0)
  await editor.getByRole('button', '引用选区', { exact: true }).press('Enter')
  await screen.getByLabel('画布反馈').fill('请解释选中的内容')
  await screen.getByRole('button', '发送反馈', { exact: true }).tap()
  await expect(screen.getByLabel('画布反馈')).toBeHidden()
  const evidence = await browser.evaluate(async () => await fetch('/__canvas/evidence').then(r => r.json()))
  expect(evidence.feedback.length).toBe(1)
  expect(evidence.feedback[0]).toContain('用户保存的修改与选区')
  expect(evidence.patches[0].baseRevision).toBe(1)
  await mkdir('artifacts/canvas-app', { recursive: true })
  await writeFile('artifacts/canvas-app/edit-reference.json', JSON.stringify({ ...evidence, initialized: methods.filter(method => method === 'ui/initialize').length }, null, 2))
  await app.screenshot('canvas-mcp-app-saved')
})

test('remote revision conflicts preserve the draft, reload is explicit, preview remains live', async ({ app, browser, screen }) => {
  await app.open('/e2e/canvas-app/index.html')
  await browser.locator('[data-canvas-frame="fixture-frame"] .canvas-frame-body').tap()
  const editor = browser.frameLocator('iframe[data-canvas-document-app]')
  await expect(editor.getByLabel('编辑文档')).toBeEnabled()
  await editor.getByLabel('编辑文档').fill('未保存的本地草稿')
  await screen.getByRole('button', 'Fixture remote edit', { exact: true }).tap()
  await expect(editor.getByLabel('编辑文档')).toHaveValue('未保存的本地草稿')
  await editor.getByRole('button', '保存修改', { exact: true }).press('Enter')
  await expect(editor.getByRole('status')).toContainText('草稿已保留')
  const conflict = await browser.evaluate(async () => await fetch('/__canvas/evidence').then(r => r.json()))
  expect(conflict.document.content).toBe('远端已保存的新版本')
  expect(conflict.patches[0].baseRevision).toBe(1)
  await app.screenshot('canvas-mcp-app-conflict')
  await editor.getByRole('button', '重新载入已保存版本', { exact: true }).press('Enter')
  await screen.getByRole('alertdialog').getByRole('button', '取消', { exact: true }).tap()
  await expect(editor.getByLabel('编辑文档')).toHaveValue('未保存的本地草稿')
  await editor.getByRole('button', '重新载入已保存版本', { exact: true }).press('Enter')
  await screen.getByRole('alertdialog').getByRole('button', '重新载入', { exact: true }).tap()
  await expect(editor.getByLabel('编辑文档')).toHaveValue('远端已保存的新版本')
  await expect(editor.getByRole('status')).toHaveText('已保存 · 第 2 版')
  await writeFile('artifacts/canvas-app/conflict.json', JSON.stringify(conflict, null, 2))
})

test('lost save response is reconciled by readback and survives reload without replaying the write', async ({ app, browser }) => {
  await app.open('/e2e/canvas-app/index.html')
  await browser.locator('[data-canvas-frame="fixture-frame"] .canvas-frame-body').tap()
  const editor = browser.frameLocator('iframe[data-canvas-document-app]')
  await expect(editor.getByLabel('编辑文档')).toBeEnabled()
  await editor.getByLabel('编辑文档').fill('丢失回执后核对的文档')
  await browser.evaluate(async () => { await fetch('/__canvas/failure', { method: 'POST', body: JSON.stringify({ dropNext: true }) }); return true })
  await editor.getByRole('button', '保存修改', { exact: true }).press('Enter')
  await expect(editor.getByRole('status')).toHaveText('已保存 · 第 2 版')
  const evidence = await browser.evaluate(async () => await fetch('/__canvas/evidence').then(r => r.json()))
  expect(evidence.patches.length).toBe(1)
  await app.open('/e2e/canvas-app/index.html?restore=1')
  await browser.locator('[data-canvas-frame="fixture-frame"] .canvas-frame-body').tap()
  await expect(editor.getByLabel('编辑文档')).toHaveValue('丢失回执后核对的文档')
  await app.screenshot('canvas-mcp-app-restored')
  await writeFile('artifacts/canvas-app/readback.json', JSON.stringify(evidence, null, 2))
})

test('forged parent messages cannot call tools and scope invalidation closes the App', async ({ app, browser, screen }) => {
  await app.open('/e2e/canvas-app/index.html')
  await browser.locator('[data-canvas-frame="fixture-frame"] .canvas-frame-body').tap()
  const editor = browser.frameLocator('iframe[data-canvas-document-app]')
  await expect(editor.getByLabel('编辑文档')).toBeEnabled()
  await browser.evaluate(() => {
    window.postMessage({ jsonrpc: '2.0', id: 42, method: 'tools/call', params: { name: 'commit_frame', arguments: { content: 'forged', expectedRevision: 1 } } }, '*')
    return true
  })
  await screen.getByRole('button', 'Fixture switch company', { exact: true }).tap()
  await expect(browser.locator('[data-canvas-app-phase]')).toHaveAttribute('data-canvas-app-phase', 'error')
  await expect(browser.locator('iframe[data-canvas-document-app][srcdoc]')).toHaveCount(0)
  const evidence = await browser.evaluate(async () => await fetch('/__canvas/evidence').then(r => r.json()))
  expect(evidence.patches.length).toBe(0)
  expect(evidence.feedback.length).toBe(0)
  await app.screenshot('canvas-mcp-app-scope-revoked')
  await writeFile('artifacts/canvas-app/isolation.json', JSON.stringify(evidence, null, 2))
})

