import { test } from '@e2e-dev/web'
import { expect } from 'e2e'

test.describe('durable questionnaire', { tags: ['web', 'questionnaire'] }, () => {
  test('trusted questionnaire binding replaces generic continuation forms', async ({ app, screen }) => {
    await app.open('/e2e/questionnaire.html?mode=native-bound')
    await expect(screen.getByRole('textbox', '补充信息', { exact: true })).toHaveCount(0)
    await expect(screen.getByText('已完成', { exact: true }).first()).toBeVisible()
    await expect(screen.getByText('请在问卷卡片中提交回答。', { exact: true }).first()).toBeVisible()
    await app.screenshot('questionnaire-single-submit-entry')
    await app.open('/e2e/questionnaire.html?mode=native-unbound')
    await expect(screen.getByRole('textbox', '补充信息', { exact: true }).first()).toBeVisible()
  })
  test('unread status blocks submission; waiting stays idle until explicit submit', async ({ app, browser, screen }) => {
    await app.open('/e2e/questionnaire.html?mode=loading')
    await expect(screen.getByLabel('学习目标')).toBeDisabled()
    await expect(screen.getByLabel('学习目标')).toBeEnabled()
    expect(await browser.locator('[data-posts]').getAttribute('data-posts')).toBe('0')
    await app.screenshot('questionnaire-waiting')
  })
  test('durable answers render read-only without answer history and refresh never posts', async ({ app, browser, screen }) => {
    await app.open('/e2e/questionnaire.html?mode=submitted')
    await expect(screen.getByLabel('学习目标')).toHaveValue('服务器已保存的目标')
    await expect(screen.getByLabel('学习目标')).toBeDisabled()
    await expect(screen.getByText('已提交', { exact: true })).toBeVisible()
    await browser.reload()
    await expect(screen.getByLabel('学习目标')).toHaveValue('服务器已保存的目标')
    expect(await browser.locator('[data-posts]').getAttribute('data-posts')).toBe('0')
    await app.screenshot('questionnaire-durable-submitted')
  })
  test('double clicks submit once; failure retries and refresh preserves accepted answers', async ({ app, browser, screen }) => {
    await app.open('/e2e/questionnaire.html?mode=retry')
    await screen.getByLabel('学习目标').fill('掌握分数')
    await browser.evaluate(() => { const button = [...document.querySelectorAll('button')].find(node => node.textContent === '提交')!; button.click(); button.click(); return true })
    await expect(screen.getByRole('alert')).toBeVisible()
    expect(await browser.locator('[data-posts]').getAttribute('data-posts')).toBe('1')
    await screen.getByRole('button', '提交', { exact: true }).tap()
    await expect(screen.getByText('已提交', { exact: true })).toBeVisible()
    expect(await browser.locator('[data-echoes]').getAttribute('data-echoes')).toBe('1')
    await browser.reload()
    await expect(screen.getByLabel('学习目标')).toHaveValue('掌握分数')
    await expect(screen.getByLabel('学习目标')).toBeDisabled()
    expect(await browser.locator('[data-posts]').getAttribute('data-posts')).toBe('2')
    await app.screenshot('questionnaire-retry-refresh')
  })
  test('a lost accepted response reconciles canonical answers before another POST', async ({ app, browser, screen }) => {
    await app.open('/e2e/questionnaire.html?mode=lost-receipt')
    await screen.getByLabel('学习目标').fill('已保存的原答案')
    await screen.getByRole('button', '提交', { exact: true }).tap()
    await expect(screen.getByRole('alert')).toBeVisible()
    await screen.getByLabel('学习目标').fill('未保存的新答案')
    await screen.getByRole('button', '提交', { exact: true }).tap()
    await expect(screen.getByText('已提交', { exact: true })).toBeVisible()
    await expect(screen.getByLabel('学习目标')).toHaveValue('已保存的原答案')
    expect(await browser.locator('[data-posts]').getAttribute('data-posts')).toBe('1')
    await app.screenshot('questionnaire-lost-receipt-canonical-answer')
  })
  test('pending submission freezes saved answers and retries only those values', async ({ app, browser, screen }) => {
    await app.open('/e2e/questionnaire.html?mode=pending')
    await expect(screen.getByLabel('学习目标')).toHaveValue('冻结的答案')
    await expect(screen.getByLabel('学习目标')).toBeDisabled()
    await expect(screen.getByText('回答已保存，正在确认提交', { exact: true })).toBeVisible()
    await screen.getByRole('button', '重试提交', { exact: true }).tap()
    await expect(screen.getByText('已提交', { exact: true })).toBeVisible()
    await expect(screen.getByLabel('学习目标')).toHaveValue('冻结的答案')
    expect(await browser.locator('[data-posts]').getAttribute('data-posts')).toBe('1')
    await app.screenshot('questionnaire-pending-recovery')
  })
  test('an exhausted resume keeps canonical answers and requires one explicit recovery', async ({ app, browser, screen }) => {
    await app.open('/e2e/questionnaire.html?mode=resuming-retry')
    await expect(screen.getByLabel('学习目标')).toHaveValue('已提交的原答案')
    await expect(screen.getByLabel('学习目标')).toBeDisabled()
    await expect(screen.getByText('回答已提交，等待继续', { exact: true })).toBeVisible()
    await browser.reload()
    await expect(screen.getByRole('button', '重试继续', { exact: true })).toBeVisible()
    expect(await browser.locator('[data-posts]').getAttribute('data-posts')).toBe('0')
    await screen.getByRole('button', '重试继续', { exact: true }).tap()
    await expect(screen.getByText('已提交', { exact: true })).toBeVisible()
    await expect(screen.getByLabel('学习目标')).toHaveValue('已提交的原答案')
    expect(await browser.locator('[data-posts]').getAttribute('data-posts')).toBe('1')
    await app.screenshot('questionnaire-resume-retry')
    await app.open('/e2e/questionnaire.html?mode=resuming-active')
    await expect(screen.getByText('回答已提交，等待继续', { exact: true })).toBeVisible()
    await expect(screen.getByRole('button', '重试继续', { exact: true })).toHaveCount(0)
    expect(await browser.locator('[data-posts]').getAttribute('data-posts')).toBe('0')
  })
  test('unavailable and foreign owner cards stay disabled; loading failure can reload', async ({ app, screen }) => {
    for (const mode of ['unavailable', 'readonly']) {
      await app.open(`/e2e/questionnaire.html?mode=${mode}`)
      await expect(screen.getByLabel('学习目标')).toBeDisabled()
      await expect(screen.getByRole('button', '提交', { exact: true })).toBeDisabled()
    }
    await app.open('/e2e/questionnaire.html?mode=load-error')
    await expect(screen.getByRole('alert')).toBeVisible()
    await screen.getByRole('button', '重新载入').tap()
    await expect(screen.getByLabel('学习目标')).toBeEnabled()
    await app.screenshot('questionnaire-state-retry')
  })
})
