import { test } from '@e2e-dev/web'
import { expect } from 'e2e'
import { memberSession, mutationPermission, testName } from './support'

test.describe('Course forum', { ...memberSession(), tags: ['web', 'learning', 'forum'] }, () => {
  test('forum follows course URLs, reload and history at mobile and desktop widths', async ({ app, screen, browser }) => {
    await app.open('/?project=e2e-classroom&view=forum')
    await expect(screen.getByRole('heading', '论坛', { exact: true })).toBeVisible()
    await expect(screen.getByRole('button', '全部', { exact: true })).toBeVisible()
    await screen.getByRole('navigation', '工作区与功能').getByRole('button', '资料', { exact: true }).tap()
    await browser.back()
    await expect(screen.getByLabel('搜索论坛')).toBeVisible()
    await browser.reload()
    await expect(screen.getByLabel('搜索论坛')).toBeVisible()
    await browser.setViewport({ width: 390, height: 844 })
    await expect(screen.getByLabel('搜索论坛')).toBeVisible()
    expect(await browser.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await app.screenshot('forum-mobile')
    await browser.setViewport({ width: 1440, height: 1000 })
    await app.screenshot('forum-desktop')
  })
  test('publish a case, comment and select it without changing the author', { skip: mutationPermission.skip }, async ({ app, screen, browser }) => {
    const title = testName('Forum case')
    await app.open('/?project=e2e-classroom&view=forum')
    await screen.getByRole('button', '发布内容', { exact: true }).tap()
    await screen.getByLabel('内容标题').fill(title)
    await screen.getByLabel('内容正文').fill('A repeatable forum case.')
    await screen.getByLabel('内容类型').selectOption({ value: 'case' })
    await screen.getByLabel('标签').fill('e2e,geometry')
    await screen.getByRole('button', '发布', { exact: true }).tap()
    const card = browser.locator('article').filter({ hasText: title })
    await expect(card).toBeVisible()
    await card.getByRole('button', '评论', { exact: true }).tap()
    await screen.getByLabel('发表评论').fill('Persisted comment')
    await screen.getByRole('button', '发送评论').tap()
    await expect(screen.getByText('Persisted comment', { exact: true })).toBeVisible()
    await browser.keyboard.press('Escape')
    await card.getByRole('button', '精选', { exact: true }).tap()
    await browser.reload()
    await screen.getByLabel('搜索论坛').fill(title)
    await expect(card).toContainText('精选案例')
    await app.screenshot('forum-case')
  })
})
