import { readFileSync } from 'node:fs'
import { test } from '@e2e-dev/web'
import { expect } from 'e2e'

test('actual public tools survive a model-only native trace with selectable stages and child folding',async ({ app,browser,screen }) => {
  const frames = JSON.parse(readFileSync(process.env.ISSUE348_SNAPSHOTS ?? '.e2e/issue348-snapshots.json','utf8'))
  const send = (name: string) => browser.evaluate(snapshot=>{ window.dispatchEvent(new CustomEvent('native-streaming-snapshot',{ detail: snapshot }));return true },frames[name])
  await browser.setViewport({ width: 390,height: 1000 })
  await app.open('/e2e/native-streaming.html')
  await send('running')
  await browser.locator('[data-slot="run-activity"] button').first().press('Enter')
  await browser.locator('[data-slot="run-activity-details"] summary').press('Enter')
  await expect(screen.getByRole('region','运行瀑布图')).toBeVisible()
  await expect(browser.locator('[data-trace-work-kind="retrieval"]')).toHaveCount(2)
  await expect(browser.locator('[data-trace-work-kind="skill"]')).toHaveCount(1)
  await expect(screen.getByRole('button','查看 子任务 详情')).toBeVisible()
  await send('completed')
  await screen.getByRole('button','收起 子任务').press('Enter')
  await expect(screen.getByRole('button','查看 更新文档 详情')).not.toBeVisible()
  await screen.getByRole('button','展开 子任务').press('Enter')
  await expect(screen.getByRole('button','查看 更新文档 详情')).toBeVisible()
  await screen.getByRole('button','技能 1',{ exact: true }).tap()
  await expect(screen.getByRole('button','查看 读取技能说明 详情')).toBeVisible()
  await expect(screen.getByRole('button','查看 查找资料 详情')).toHaveCount(0)
  await screen.getByRole('button','全部 7',{ exact: true }).tap()
  for (const phase of ['completed','replay']) {
    await send(phase)
    await expect(browser.locator('[data-trace-work-kind="retrieval"]')).toHaveCount(2)
    await expect(browser.locator('[data-trace-span-id="child"]')).toHaveCount(1)
    await expect(browser.locator('[data-trace-work-kind="skill"] [data-trace-lane]')).toHaveAttribute('data-trace-start','250')
    await expect(browser.locator('[data-trace-work-kind="skill"] [data-trace-lane]')).toHaveAttribute('data-trace-end','500')
  }
  expect(await browser.evaluate(()=>document.querySelector('[data-slot="trace-waterfall"]')?.textContent ?? '')).not.toMatch(/PRIVATE|private-call|Bearer|sk-/)
  expect(await browser.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await app.screenshot('agent-work-trace-public-tools-and-child')
  await browser.reload();await send('replay')
  await browser.locator('[data-slot="run-activity"] button').first().press('Enter')
  await browser.locator('[data-slot="run-activity-details"] summary').press('Enter')
  await expect(browser.locator('[data-trace-work-kind="retrieval"]')).toHaveCount(2)
  await screen.getByRole('button','子任务 1',{ exact: true }).tap()
  await expect(screen.getByRole('button','查看 子任务 详情')).toBeVisible()
  await expect(screen.getByRole('button','查看 读取技能说明 详情')).toHaveCount(0)
  await app.screenshot('agent-work-trace-child-filter-reload')
})

test('real local Worker skill/retrieval receipts and authorized queued child are visible after replay',async ({ app,browser,screen }) => {
  const frames = JSON.parse(readFileSync(process.env.ISSUE348_REAL_SNAPSHOTS ?? '.e2e/issue348-real-snapshots.json','utf8'))
  const send = (name: string) => browser.evaluate(snapshot=>{ window.dispatchEvent(new CustomEvent('native-streaming-snapshot',{ detail: snapshot }));return true },frames[name])
  await app.open('/e2e/native-streaming.html')
  await send('history')
  await browser.locator('[data-slot="run-activity"] button').first().press('Enter')
  await browser.locator('[data-slot="run-activity-details"] summary').press('Enter')
  for (const phase of ['history','rescued','replay','reload']) {
    await send(phase)
    await expect(browser.locator('[data-trace-work-kind="skill"]')).toHaveCount(1)
    await expect(browser.locator('[data-trace-work-kind="retrieval"]')).toHaveCount(1)
    await expect(screen.getByRole('button','查看 读取技能说明 详情')).toBeVisible()
    await expect(screen.getByRole('button','查看 查找资料 详情')).toBeVisible()
    const actual = await browser.evaluate(()=>[...document.querySelectorAll<HTMLElement>('[data-trace-work-kind] > [data-trace-row] > [data-trace-lane]')]
      .map(node=>({ start: Number(node.dataset.traceStart),end: Number(node.dataset.traceEnd) })))
    expect(actual.length).toBe(2)
    expect(actual.every(span=>Number.isFinite(span.start) && span.end >= span.start)).toBe(true)
  }
  await app.screenshot('agent-work-trace-real-worker-receipts')
  await browser.reload();await send('child')
  await browser.locator('[data-slot="run-activity"] button').first().press('Enter')
  await browser.locator('[data-slot="run-activity-details"] summary').press('Enter')
  await expect(screen.getByRole('region','运行瀑布图')).toBeVisible()
  await expect(browser.locator('[data-trace-work-kind="subtask"]')).toHaveCount(1)
  await expect(browser.locator('[data-trace-work-kind="subtask"] > [data-trace-row] > [data-trace-lane]')).toHaveAttribute('data-trace-start','')
  await expect(browser.locator('[data-trace-work-kind="subtask"] > [data-trace-row] > [data-trace-lane]')).toHaveAttribute('data-trace-end','')
  expect(await browser.evaluate(()=>document.querySelector('[data-slot="trace-waterfall"]')?.textContent ?? '')).not.toMatch(/PRIVATE_TOOL_OUTPUT|leaseToken|instructionsSha256/)
  await app.screenshot('agent-work-trace-real-authorized-child')
})
