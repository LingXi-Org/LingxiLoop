import { test } from '@e2e-dev/web'
import { expect } from 'e2e'
import { nativeBlock, nativeLink } from './native'
import { assertNativeReducedMotion } from '../native-reduced-motion'
test('case GFM imports retain literal HTML text, currency and setext headings',async({app,browser,screen})=>{
  await app.open('/e2e/content-editor.html?format=markdown')
  const editor=screen.getByLabel('原生正文',{exact:true})
  await expect(editor).toContainText('literal <em>sample</em>',{timeout:120000})
  await expect(editor).toContainText('$5 and $3')
  await expect(editor.getByRole('heading','Case heading',{exact:true})).toBeVisible()
  await expect(browser.locator('[aria-label="原生正文"] em')).toHaveCount(0)
  await editor.focus()
  await browser.keyboard.press('Control+End')
  await browser.keyboard.press('Enter')
  await browser.keyboard.type('追加记录')
  await screen.getByRole('button','保存并重新打开',{exact:true}).tap()
  const saved=await browser.evaluate(()=>JSON.parse(localStorage.getItem('native-219')!).document)
  expect(saved.legacyMarkdown).toContain('literal <em>sample</em>')
  expect(JSON.stringify(saved.blocks)).toContain('literal <em>sample</em>')
  await expect(editor).toContainText('literal <em>sample</em>')
  await app.screenshot('case-legacy-literal-roundtrip')
})
test('upstream native schema, slash menus, tables, blocks, undo and lossless reopen',async({app,browser,screen})=>{
  await app.open('/e2e/content-editor.html')
  if (process.env.E2E_NATIVE_REDUCED_MOTION === '1') await assertNativeReducedMotion(browser)
  const editor=()=>screen.getByLabel('原生正文',{exact:true})
  await expect(editor()).toBeVisible({timeout:120000})
  await expect(editor()).toContainText('原有内容')
  await expect(editor()).toContainText('原价 $5，折后 $3。')
  expect(await browser.evaluate(()=>Array.from(document.querySelectorAll('[aria-label="原生正文"] [data-content-type="paragraph"]')).some(node=>node.textContent?.includes('保持普通段落')))).toBe(true)
  expect(await browser.evaluate(()=>Boolean(document.querySelector('[aria-label="原生正文"] [data-content-type="paragraph"] br')))).toBe(true)
  await expect(browser.locator('[aria-label="原生正文"] [data-content-type="checkListItem"]')).toBeVisible()
  await expect(browser.locator('[aria-label="原生正文"] math').first()).toBeVisible()
  await expect(browser.locator('[aria-label="原生正文"] [data-content-type="diagram"] svg')).toBeVisible()
  await editor().focus()
  await browser.keyboard.press('Control+End')
  await browser.keyboard.press('Enter')
  await browser.keyboard.type('追加中文')
  await browser.keyboard.press('Control+z')
  await expect(editor()).not.toContainText('追加中文')
  await browser.keyboard.press('Control+Shift+z')
  await expect(editor()).toContainText('追加中文')
  await nativeBlock(browser,screen,'原生正文','table','表格')
  await browser.keyboard.type('观察')
  await browser.keyboard.press('Tab')
  await browser.keyboard.type('结论')
  await screen.getByRole('button','保存并重新打开',{exact:true}).tap()
  await expect(browser.locator('[aria-label="已保存文档"] table')).toBeVisible()
  const before=await browser.evaluate(()=>JSON.parse(localStorage.getItem('native-219')!))
  expect(before.document.blocks.some((block:{type:string})=>block.type==='table')).toBe(true)
  expect(before.document.legacyMarkdown).toContain('$x^2$')
  expect(before.document.blocks.some((block:{content?:{type:string;content?:{text:string}[]}[]})=>Array.isArray(block.content)&&block.content.some(item=>item.type==='math'))).toBe(true)
  await expect(editor()).toContainText('结论')
  await screen.getByRole('button','保存并重新打开',{exact:true}).tap()
  expect(await browser.evaluate(()=>JSON.parse(localStorage.getItem('native-219')!).document)).toEqual(before.document)
  await app.screenshot('native-desktop-roundtrip')
  await browser.setViewport({width:390,height:900})
  expect(await browser.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await app.screenshot('native-mobile-table')
})

test('all 14 default blocks and official free math and diagram blocks remain insertable',async({app,browser,screen})=>{
  await app.open('/e2e/content-editor.html')
  const editor=()=>screen.getByLabel('原生正文',{exact:true})
  await expect(editor()).toBeVisible({timeout:120000})
  for(const [query,title,type] of [
    ['h2','二级标题','heading'],['paragraph','段落','paragraph'],['bullet','无序列表','bulletListItem'],
    ['number','有序列表','numberedListItem'],['checklist','检查清单','checkListItem'],['折叠','可折叠列表','toggleListItem'],
    ['code','代码块','codeBlock'],['quote','引用','quote'],['table','表格','table'],['image','图片','image'],
    ['audio','音频','audio'],['video','视频','video'],['file','文件','file'],['divider','分隔线','divider'],['公式','块级公式','mathBlock'],['mermaid','图表','diagram'],
  ]) {
    await editor().fill('')
    await nativeBlock(browser,screen,'原生正文',query,title)
    await browser.keyboard.press('Escape')
    await screen.getByRole('button','保存并重新打开',{exact:true}).tap()
    const blocks=await browser.evaluate(()=>JSON.parse(localStorage.getItem('native-219')!).document?.blocks.map((block:{type:string})=>block.type))
    expect(blocks).toContain(type)
  }
  await app.open('/e2e/content-editor.html')
  await expect(editor()).toContainText('原有内容')
  await editor().fill('')
  await editor().focus()
  await browser.keyboard.press('Control+Alt+0')
  await expect.poll(()=>browser.evaluate(()=>{
    const anchor=window.getSelection()?.anchorNode
    const element=anchor instanceof Element ? anchor : anchor?.parentElement
    if(!element?.closest('[aria-label="原生正文"]')) return null
    return element.closest('[data-content-type]')?.getAttribute('data-content-type') ?? null
  })).toBe('paragraph')
  await browser.keyboard.press('Control+b')
  await browser.keyboard.type('原生粗体')
  await expect(browser.locator('[aria-label="原生正文"] strong')).toHaveText('原生粗体')
  await browser.keyboard.press('Control+b')
  await screen.getByRole('button','保存并重新打开',{exact:true}).tap()
  expect(await browser.evaluate(()=>JSON.stringify(JSON.parse(localStorage.getItem('native-219')!).document.blocks))).toContain('"bold":true')
  await app.screenshot('default-native-controls')
})

test('native formatting, links, emoji, block menu and table operations remain complete',async({app,browser,screen})=>{
  await app.open('/e2e/content-editor.html')
  if (process.env.E2E_NATIVE_REDUCED_MOTION === '1') await assertNativeReducedMotion(browser)
  const editor=()=>screen.getByLabel('原生正文',{exact:true})
  await expect(editor()).toBeVisible({timeout:120000})
  await editor().fill('原生格式')
  await browser.keyboard.press('Control+a')
  for(const label of ['加粗','斜体','下划线','删除线']) await screen.getByRole('button',label,{exact:true}).tap()
  await screen.getByRole('button','颜色',{exact:true}).tap()
  await browser.locator('[data-test="text-color-red"]').tap()
  await screen.getByRole('button','居中',{exact:true}).tap()
  await screen.getByRole('button','保存并重新打开',{exact:true}).tap()
  const styled=await browser.evaluate(()=>JSON.parse(localStorage.getItem('native-219')!).document.blocks[0])
  expect(styled.props.textAlignment).toBe('center')
  for(const style of ['bold','italic','underline','strike']) expect(styled.content[0].styles[style]).toBe(true)
  expect(styled.content[0].styles.textColor).toBe('red')
  // Native code intentionally excludes formatting marks; test it separately.
  await editor().focus()
  await browser.keyboard.press('Control+a')
  await browser.keyboard.press('Control+e')
  await screen.getByRole('button','保存并重新打开',{exact:true}).tap()
  expect(await browser.evaluate(()=>JSON.parse(localStorage.getItem('native-219')!).document.blocks[0].content[0].styles.code)).toBe(true)
  await nativeLink(browser,screen,'原生正文','https://example.org/native-219')
  await expect(browser.locator('[aria-label="原生正文"] a[href="https://example.org/native-219"]')).toBeVisible()
  await nativeBlock(browser,screen,'原生正文','emoji','表情符号')
  await expect(screen.getByRole('grid')).toBeVisible()
  await screen.getByRole('grid').getByRole('option').first().tap()
  await browser.locator('[aria-label="原生正文"] [data-content-type="paragraph"]').first().hover()
  await screen.getByRole('button','打开菜单',{exact:true}).tap()
  await expect(screen.getByRole('menuitem','删除',{exact:true})).toBeVisible()
  await expect(screen.getByRole('menuitem','颜色',{exact:true})).toBeVisible()
  await app.screenshot('native-block-menu')
  await browser.keyboard.press('Escape')
  await nativeBlock(browser,screen,'原生正文','table','表格')
  const dimensions=()=>browser.evaluate(()=>{
    const table=document.querySelector<HTMLTableElement>('[aria-label="原生正文"] table')!
    return {rows:table.rows.length,columns:table.rows[0].cells.length}
  })
  const before=await dimensions()
  await browser.locator('[aria-label="原生正文"] table tr:first-child :is(th,td)').first().hover()
  await browser.locator('[data-test="tableHandle"]').first().tap()
  await screen.getByRole('menuitem',/右侧添加列|下方添加行/).tap()
  const after=await dimensions()
  expect(after.rows>before.rows||after.columns>before.columns).toBe(true)
  await screen.getByRole('button','保存并重新打开',{exact:true}).tap()
  expect(await browser.evaluate(()=>JSON.stringify(JSON.parse(localStorage.getItem('native-219')!).document.blocks))).toMatch(/\p{Extended_Pictographic}/u)
  await app.screenshot('native-formatting-link-emoji-table')
  await browser.setViewport({width:390,height:900})
  await editor().focus()
  await browser.keyboard.press('Control+Home')
  await browser.keyboard.press('Shift+End')
  await expect.poll(()=>browser.evaluate(()=>window.getSelection()?.toString() ?? null)).toBe('原生格式')
  await expect(screen.getByRole('button','颜色',{exact:true})).toBeVisible()
  const toolbar=await browser.evaluate(()=>{
    const node=document.querySelector<HTMLElement>('.bn-formatting-toolbar')!
    const rect=node.getBoundingClientRect()
    return {left:rect.left,right:rect.right,viewport:innerWidth,overflow:getComputedStyle(node).overflowX,scroll:node.scrollWidth,width:node.clientWidth}
  })
  expect(toolbar.left).toBeGreaterThanOrEqual(0)
  expect(toolbar.right).toBeLessThanOrEqual(toolbar.viewport)
  if(toolbar.scroll>toolbar.width) expect(toolbar.overflow).toBe('auto')
  await screen.getByRole('button','颜色',{exact:true}).tap()
  await expect(browser.locator('[data-test="text-color-red"]')).toBeVisible()
  await expect.poll(()=>browser.evaluate(()=>document.getAnimations().filter(animation=>animation.playState==='running'&&animation.effect?.getTiming().iterations!==Infinity).length)).toBe(0)
  await app.screenshot('native-mobile-formatting-controls')
})
