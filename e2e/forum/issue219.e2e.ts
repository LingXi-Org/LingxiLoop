test('legacy submission, native teacher feedback media and private history keep the same audience',async({app,browser,screen})=>{
  await openAs(app,browser,screen,'student')
  await screen.getByRole('link','Memos 详情与作答验收',{exact:true}).tap()
  await screen.getByLabel('作业内容',{exact:true}).fill('Issue219 作答：两个全等三角形拼成长方形。')
  await screen.getByLabel('选择学习对话').tap()
  await screen.getByRole('option','我的作业学习对话',{exact:true}).tap()
  await browser.locator('fieldset summary').filter({hasText:'我用两个全等三角形'}).tap()
  await screen.getByRole('checkbox','引用这段对话').check()
  await screen.getByRole('button','提交作业',{exact:true}).tap()
  await expect(screen.getByText('作业已提交，正在生成学习评价。',{exact:true})).toBeVisible()
  await openAs(app,browser,screen)
  await screen.getByRole('link','Memos 详情与作答验收',{exact:true}).tap()
  await screen.getByLabel('按学生姓名检索').fill('Forum student')
  await screen.getByRole('button',/Forum student/).tap()
  await screen.getByLabel('反馈：Forum student',{exact:true}).fill('Issue219 教师反馈：解释完整，保留观察图。')
  await nativeUpload(browser,screen,'反馈：Forum student',file('./diagram.png'))
  await screen.getByRole('button','保存反馈',{exact:true}).tap()
  await expect(screen.getByText('Issue219 教师反馈：解释完整，保留观察图。',{exact:true})).toBeVisible()
  const versions=await browser.evaluate(async()=> (await fetch('/api/courses/e2e-course/forum/post/issue146-assignment/submissions?learnerId=forum-student',{headers:{'x-company-id':'e2e-school'}}).then(r=>r.json())).items)
  expect(versions[0].editorDocument.format).toBe('blocknote')
  const feedback=versions[0].feedback.find((f:{body:string})=>f.body.includes('Issue219 教师反馈'))
  expect(feedback.editorDocument.format).toBe('blocknote')
  expect(feedback.attachments).toHaveLength(1)
  const asset=`/api/files?key=${encodeURIComponent(feedback.attachments[0].key)}`
  await app.screenshot('private-feedback-native-media')
  await openAs(app,browser,screen,'student')
  expect(await browser.evaluate(async url=>(await fetch(url)).status,asset)).toBe(200)
  await screen.getByRole('link','Memos 详情与作答验收',{exact:true}).tap()
  await expect(screen.getByText('Issue219 教师反馈：解释完整，保留观察图。',{exact:true})).toBeVisible()
  await openAs(app,browser,screen,'peer')
  expect(await browser.evaluate(async url=>(await fetch(url)).status,asset)).toBe(404)
  await screen.getByRole('link','Memos 详情与作答验收',{exact:true}).tap()
  await expect(screen.getByText('Issue219 教师反馈：解释完整，保留观察图。',{exact:true})).toHaveCount(0)
  await app.screenshot('peer-cannot-read-private-feedback')
})
