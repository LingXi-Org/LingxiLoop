import { fileURLToPath } from 'node:url'
import { test, type Browser } from '@e2e-dev/web'
import { expect, type App, type Screen } from 'e2e'
import { nativeBlock, nativeUpload } from '../content-editor/native'

const url='/?project=e2e-classroom&view=forum'
const file=(name:string)=>fileURLToPath(new URL(name,import.meta.url))
async function openAs(app:App,browser:Browser,screen:Screen,role='teacher') {
  await app.open('/')
  await browser.evaluate(async role=>{localStorage.setItem('lingxiloop-theme','light');return(await fetch(`/api/fixture-role/${role}`)).ok},role)
  await app.open(url)
  await expect(screen.getByLabel('搜索学习论坛')).toBeVisible({timeout:120000})
}
async function posts(browser:Browser,search:string) {
  return browser.evaluate(async search=>(await fetch(`/api/courses/e2e-course/forum?search=${encodeURIComponent(search)}`,{headers:{'x-company-id':'e2e-school'}}).then(r=>r.json())).items,search)
}
async function fixture(browser:Browser,path:string) {
  expect(await browser.evaluate(async path=>(await fetch(path,{method:'POST'})).ok,path)).toBe(true)
}

