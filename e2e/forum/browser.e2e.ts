  await screen.getByText('历史版本（1）',{ exact: true }).tap()
  await expect(screen.getByText('Original student answer',{ exact: true })).toBeVisible()
  await expect(screen.getByRole('link','submission.txt',{ exact: true })).toBeVisible()
