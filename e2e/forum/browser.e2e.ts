  await expect(browser.locator('[data-memo-editor-preview] strong')).toContainText('草稿恢复与快捷键')
  await browser.reload()
  await screen.getByRole('button','发布内容',{ exact: true }).tap()
  await expect(screen.getByLabel('内容标题')).toHaveValue('Student geometry case')
