import { test } from '@e2e-dev/web'
import { expect } from 'e2e'
import { fileURLToPath } from 'node:url'

test('forum history, public resources, student versions, private files, teacher moderation and closure', async ({ app,screen,browser }) => {
  const openAs = async (role: 'teacher' | 'student' | 'peer') => {
    await app.open('/')
    await browser.evaluate(async role => (await fetch(`/api/fixture-role/${role}`)).ok, role)
    await app.open('/?project=e2e-classroom&view=forum')
    await expect(screen.getByLabel('搜索论坛')).toBeVisible()
  }
  await openAs('student')
  await expect(screen.getByText('Historical public resource',{ exact: true })).toBeVisible()
  await screen.getByRole('navigation','工作区与功能').getByRole('button','资料',{ exact: true }).tap()
  await browser.back()
  await expect(screen.getByLabel('搜索论坛')).toBeVisible()
  await browser.reload()
  await expect(screen.getByLabel('搜索论坛')).toBeVisible()
  const homework = browser.locator('article').filter({ hasText: 'Forum homework' })
  await homework.getByRole('button','提交作业',{ exact: true }).tap()
  await screen.getByLabel('作业内容').fill('Original student answer')
  await screen.getByLabel('链接（每行一个）').fill('https://example.com/my-homework')
  await screen.getByLabel('附件',{ exact: true }).setInputFiles([fileURLToPath(new URL('./submission.txt',import.meta.url))])
  await expect(screen.getByRole('button','移除附件：submission.txt')).toBeVisible()
  await screen.getByRole('dialog').getByRole('button','提交作业',{ exact: true }).tap()
  await expect(screen.getByText('作业已提交',{ exact: true })).toBeVisible()
  await screen.getByLabel('作业内容').fill('Revised student answer')
  await screen.getByRole('dialog').getByRole('button','提交作业',{ exact: true }).tap()
  await expect(screen.getByText('Revised student answer',{ exact: true })).toBeVisible()
  await screen.getByText('历史版本（1）',{ exact: true }).tap()
  await expect(screen.getByText('Original student answer',{ exact: true })).toBeVisible()
  await expect(screen.getByRole('link','submission.txt',{ exact: true })).toBeVisible()
  const file = await screen.getByRole('link','submission.txt',{ exact: true }).getAttribute('href')
  expect(await browser.evaluate(async url => (await fetch(url!)).status,file)).toBe(200)
  await app.screenshot('student-submission-history')
  await browser.keyboard.press('Escape')
  await screen.getByRole('button','发布内容',{ exact: true }).tap()
  await screen.getByLabel('内容标题').fill('Student geometry case')
  await screen.getByLabel('内容正文').fill('A student-owned public example.')
  await screen.getByLabel('内容类型').tap()
  await screen.getByRole('option','作品案例').tap()
  await screen.getByLabel('标签').fill('geometry')
  await screen.getByRole('button','发布',{ exact: true }).tap()
  const card = browser.locator('article').filter({ hasText: 'Student geometry case' })
  await card.getByRole('button','评论',{ exact: true }).tap()
  await screen.getByLabel('发表评论').fill('A persisted discussion')
  await screen.getByRole('button','发送评论').tap()
  await expect(screen.getByText('A persisted discussion',{ exact: true })).toBeVisible()
  await browser.keyboard.press('Escape')
  await openAs('peer')
  expect(await browser.evaluate(async url => (await fetch(url!)).status,file)).toBe(404)
  await homework.getByRole('button','提交作业',{ exact: true }).tap()
  await expect(screen.getByText('还没有提交记录。',{ exact: true })).toBeVisible()
  await browser.keyboard.press('Escape')
  await openAs('teacher')
  await screen.getByRole('button',/^切换工作区/).tap()
  await screen.getByRole('menuitem').filter({ hasText: 'Other Forum Course' }).tap()
  await expect(screen.getByLabel('搜索论坛')).toBeVisible()
  await expect(screen.getByText('Student geometry case',{ exact: true })).toBeHidden()
  await screen.getByRole('button',/^切换工作区/).tap()
  await screen.getByRole('menuitem').filter({ hasText: 'E2E Classroom' }).tap()
  await expect(card).toBeVisible()
  await card.getByRole('button','精选',{ exact: true }).tap()
  await expect(card).toContainText('精选案例')
  await expect(card).toContainText('Forum student')
  await homework.getByRole('button','查看提交',{ exact: true }).tap()
  await expect(screen.getByText('Revised student answer',{ exact: true })).toBeVisible()
  expect(await browser.evaluate(async url => (await fetch(url!)).status,file)).toBe(200)
  await browser.keyboard.press('Escape')
  await homework.getByRole('button','关闭作业',{ exact: true }).tap()
  await expect(homework).toContainText('已关闭')
  await openAs('student')
  await homework.getByRole('button','查看提交记录',{ exact: true }).tap()
  await expect(screen.getByText('作业已关闭，停止接收提交。',{ exact: true })).toBeVisible()
  await expect(screen.getByLabel('作业内容')).toBeHidden()
  await browser.keyboard.press('Escape')
  await browser.setViewport({ width: 390,height: 844 })
  await browser.evaluate(() => { document.documentElement.classList.add('dark'); return true })
  await screen.getByLabel('搜索论坛').fill('Student geometry case')
  await expect(card).toBeVisible()
  await browser.keyboard.press('Tab')
  expect(await browser.evaluate(() => document.activeElement?.tagName !== 'BODY')).toBe(true)
  expect(await browser.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await app.screenshot('forum-mobile-dark-keyboard')
  await browser.setViewport({ width: 1440,height: 1000 })
  await browser.evaluate(() => { document.documentElement.classList.remove('dark'); return true })
  await screen.getByLabel('搜索论坛').fill('')
  await expect(homework).toBeVisible()
  await app.screenshot('forum-desktop')
})
