  await screen.getByLabel('内容类型').tap()
  await screen.getByRole('option','作品案例',{ exact: true }).tap()
  await screen.getByLabel('标签').fill('geometry')
  await screen.getByLabel('附件',{ exact: true }).setInputFiles([fileURLToPath(new URL('./diagram.png',import.meta.url))])
  await expect(screen.getByRole('button','移除附件：diagram.png')).toBeVisible()
