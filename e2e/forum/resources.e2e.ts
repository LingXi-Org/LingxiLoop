import { fileURLToPath } from 'node:url'
import { test } from '@e2e-dev/web'
import { expect } from 'e2e'

// Real project-source routes and PostgreSQL; ingestion is deliberately left queued.
test('independent forum library, upload, filtering, privacy and responsive navigation', async ({ app, browser, screen }) => {
  await app.open('/')
  await browser.evaluate(async () => { localStorage.setItem('lingxiloop-theme', 'light'); return (await fetch('/api/fixture-role/teacher')).ok })
  await app.open('/?project=e2e-classroom&view=forum')
  await screen.getByRole('navigation', '学习论坛版块').getByRole('button', '资料', { exact: true }).tap()
  await expect(screen.getByRole('heading', '课程资料库', { exact: true })).toBeVisible()
  await expect(screen.getByRole('region', '发布学习论坛内容')).toHaveCount(0)
  await expect(screen.getByRole('complementary', '学习论坛侧栏')).toBeVisible()
  await expect(screen.getByRole('button', '打开资料：Historical public resource')).toBeVisible()
  await app.screenshot('resources-desktop-light')

  await screen.getByRole('button', '上传资料', { exact: true }).tap()
  const dialog = screen.getByRole('dialog')
  await expect.poll(() => browser.evaluate(() => { const dialog = document.querySelector('[role="dialog"]'); return dialog ? getComputedStyle(dialog).opacity : '0' })).toBe('1')
  await app.screenshot('resources-upload-dialog')
  await browser.evaluate(async () => (await fetch('/api/fixture-fail-source-upload', { method: 'POST' })).ok)
  await dialog.getByLabel('选择资料文件').setInputFiles(['./submission.txt', './resource-note.md'].map(path => fileURLToPath(new URL(path, import.meta.url))))
  await dialog.getByRole('button', '上传 2 个文件', { exact: true }).tap()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await expect(dialog.getByRole('list', '待上传文件')).toContainText('submission.txt')
  await dialog.getByRole('button', '上传 2 个文件', { exact: true }).tap()
  await expect(screen.getByRole('button', '打开资料：submission.txt')).toBeVisible()
  await screen.getByRole('button', '上传资料', { exact: true }).tap()
  await dialog.getByRole('tab', '粘贴文本').tap()
  await dialog.getByLabel('资料标题').fill('课堂阅读笔记')
  await dialog.getByLabel('文本内容').fill('这是一份通过独立资料库创建的课程阅读笔记。')
  await dialog.getByRole('button', '添加并处理').tap()
  await expect(screen.getByRole('button', '打开资料：课堂阅读笔记')).toBeVisible()
  expect(await browser.evaluate(async () => { const sources = await (await fetch('/api/projects/e2e-classroom/sources', { headers: { 'x-company-id': 'e2e-school', 'x-project-id': 'e2e-classroom' } })).json(); return sources.filter((source: { kind: string }) => source.kind === 'file').length })).toBe(2)
  await screen.getByRole('button', '上传资料', { exact: true }).tap()
  await dialog.getByRole('tab', '网页链接').tap()
  await dialog.getByLabel('资料标题').fill('课程阅读网站')
  await dialog.getByLabel('网页地址').fill('https://example.org/reading')
  await dialog.getByRole('button', '添加并处理').tap()
  await expect(screen.getByRole('button', '打开资料：课程阅读网站')).toBeVisible()
  await screen.getByLabel('搜索资料').fill('不存在的资料')
  await expect(screen.getByText('没有找到匹配的资料', { exact: true })).toBeVisible()
  await screen.getByRole('button', '清除筛选', { exact: true }).tap()
  await screen.getByRole('button', '文件', { exact: true }).tap()
  await expect(screen.getByRole('button', '打开资料：submission.txt')).toBeVisible()
  await expect(screen.getByRole('button', '打开资料：课堂阅读笔记')).toHaveCount(0)
  await screen.getByRole('button', '全部资料', { exact: true }).tap()
  await screen.getByRole('button', '网格视图').tap()
  await app.screenshot('resources-grid-light')
  await screen.getByRole('button', '资料操作：课堂阅读笔记').tap()
  await screen.getByRole('menuitem', '重命名', { exact: true }).tap()
  await screen.getByLabel('名称', { exact: true }).fill('课堂阅读指南')
  await screen.getByRole('button', '保存', { exact: true }).tap()
  await screen.getByRole('button', '打开资料：课堂阅读指南').tap()
  await expect(screen.getByRole('dialog')).toContainText('课程成员可见')
  await browser.keyboard.press('Escape')
  await browser.evaluate(() => { document.documentElement.classList.remove('light'); document.documentElement.classList.add('dark'); return true })
  await app.screenshot('resources-desktop-dark')
  await browser.setViewport({ width: 390, height: 844 })
  await expect(screen.getByRole('heading', '课程资料库')).toBeVisible()
  expect(await browser.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(browser.locator('[data-sonner-toast]').first()).toBeHidden()
  await app.screenshot('resources-mobile-dark')
  await screen.getByRole('button', '打开学习论坛导航').tap()
  await expect(screen.getByRole('button', '资料', { exact: true })).toHaveAttribute('aria-pressed', 'true')
  await screen.getByRole('button', '自由讨论', { exact: true }).tap()
  await expect(screen.getByRole('region', '发布学习论坛内容')).toBeVisible()

  await browser.setViewport({ width: 1440, height: 1000 })
  await browser.evaluate(async () => (await fetch('/api/fixture-role/student')).ok)
  await app.open('/?project=e2e-classroom&view=forum')
  await screen.getByRole('button', '资料', { exact: true }).tap()
  await screen.getByRole('button', '上传资料', { exact: true }).tap()
  await expect(dialog).toContainText('仅自己可见')
  await dialog.getByRole('tab', '粘贴文本').tap()
  await dialog.getByLabel('资料标题').fill('学生私人笔记')
  await dialog.getByLabel('文本内容').fill('仅当前学生能够访问的笔记。')
  await dialog.getByRole('button', '添加并处理').tap()
  await expect(screen.getByRole('button', '打开资料：学生私人笔记')).toBeVisible()
  await browser.evaluate(async () => (await fetch('/api/fixture-role/peer')).ok)
  await browser.reload()
  await screen.getByRole('button', '资料', { exact: true }).tap()
  await expect(screen.getByRole('button', '打开资料：课堂阅读指南')).toBeVisible()
  await expect(screen.getByRole('button', '打开资料：学生私人笔记')).toHaveCount(0)
  await app.screenshot('resources-peer-shared-only')
})
