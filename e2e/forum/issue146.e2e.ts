import { test } from '@e2e-dev/web'
import { expect } from 'e2e'

// Real API/PostgreSQL; recorded canonical IM. See docs/issue-146-validation.md.
test('Memos page navigation, collapsed full-roster search, frozen references and mandatory assessment',async({app,screen,browser})=>{
  const openAs=async(role:string)=>{
    await app.open('/');await browser.evaluate(async role=>{localStorage.setItem('lingxiloop-theme','light');return(await fetch(`/api/fixture-role/${role}`)).ok},role)
    await app.open('/?project=e2e-classroom&view=forum')
    await expect(screen.getByLabel('搜索学习论坛')).toBeVisible({timeout:120000})
  }
  await openAs('teacher')
  await screen.getByLabel('搜索学习论坛').fill('Memos 详情')
  await screen.getByRole('link','Memos 详情与作答验收',{exact:true}).tap()
  await expect(browser.locator('[data-memo-detail]')).toBeVisible()
  await expect(screen.getByRole('dialog')).toBeHidden()
  expect(await browser.evaluate(()=>new URL(location.href).searchParams.get('post'))).toBe('issue146-assignment')
  await expect(screen.getByLabel('按学生姓名检索')).toBeVisible()
  await expect.poll(()=>browser.evaluate(()=>document.querySelectorAll('[aria-label="提交学生列表"] [aria-expanded="false"]').length)).toBe(50)
  await expect(screen.getByText('历史长作答。'.repeat(1000),{exact:true})).toBeHidden()
  await screen.getByLabel('按学生姓名检索').fill('跨页学生')
  const row=screen.getByRole('button',/跨页学生/)
  await expect(row).toBeVisible()
  await row.tap()
  await expect(screen.getByText('历史长作答。'.repeat(1000),{exact:true})).toBeVisible()
  await screen.getByRole('button','收起作答',{exact:true}).tap()
  await expect(screen.getByLabel('按学生姓名检索')).toHaveValue('跨页学生')
  await app.screenshot('issue146-desktop-collapsed-search')
  await screen.getByRole('button','清空检索',{exact:true}).tap()
  await screen.getByLabel('按学生姓名检索').fill('没有这个学生')
  await expect(screen.getByText('没有符合检索条件的学生。',{exact:true})).toBeVisible()
  await screen.getByRole('link','返回学习论坛',{exact:true}).tap()
  await expect(screen.getByLabel('搜索学习论坛')).toHaveValue('Memos 详情')
  await screen.getByRole('link','Memos 详情与作答验收',{exact:true}).tap()
  await browser.reload()
  await expect(browser.locator('[data-memo-detail]')).toBeVisible()
  await expect(screen.getByRole('dialog')).toBeHidden()
  await openAs('student')
  await screen.getByRole('link','Memos 详情与作答验收',{exact:true}).tap()
  await screen.getByLabel('作业内容').fill('两个全等三角形组成一个长方形，所以底8高5时面积是20。')
  await expect(screen.getByRole('button','提交作业',{exact:true})).toBeDisabled()
  const rejected=await browser.evaluate(async()=>{
    const base='/api/courses/e2e-course/forum/post/issue146-assignment/submit'
    const response=await fetch(base,{method:'POST',headers:{'Content-Type':'application/json','x-company-id':'e2e-school'},body:JSON.stringify({answer:'No evidence',idempotencyKey:'missing-evidence'})})
    return response.status
  })
  expect(rejected).toBe(400)
  await screen.getByLabel('选择学习对话').tap()
  await screen.getByRole('option','我的作业学习对话',{exact:true}).tap()
  await browser.locator('fieldset summary').filter({hasText:'我用两个全等三角形'}).tap()
  await screen.getByRole('checkbox','引用这段对话').check()
  await screen.getByRole('button','提交作业',{exact:true}).tap()
  await expect(screen.getByText('作业已提交，正在生成学习评价。',{exact:true})).toBeVisible()
  await app.screenshot('issue146-student-evidence-submission')
  await openAs('teacher')
  await screen.getByRole('link','Memos 详情与作答验收',{exact:true}).tap()
  await screen.getByLabel('按学生姓名检索').fill('Forum student')
  await expect(screen.getByText('评价生成中',{exact:true})).toBeVisible()
  await screen.getByRole('link','对话 1',{exact:true}).tap()
  await expect(screen.getByText('我用两个全等三角形拼成长方形，所以面积是底乘高的一半。',{exact:true})).toBeVisible()
  await app.screenshot('issue146-teacher-reference-expanded')
  await screen.getByRole('button','收起作答',{exact:true}).tap()
  await browser.setViewport({width:390,height:844})
  await browser.evaluate(()=>{document.documentElement.classList.remove('light');document.documentElement.classList.add('dark');return true})
  await screen.getByRole('button',/Forum student/).focus()
  await browser.keyboard.press('Enter')
  await expect(screen.getByText('两个全等三角形组成一个长方形，所以底8高5时面积是20。',{exact:true})).toBeVisible()
  expect(await browser.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await app.screenshot('issue146-mobile-dark-keyboard')
  await openAs('peer')
  await screen.getByRole('link','Memos 详情与作答验收',{exact:true}).tap()
  await expect(screen.getByText('两个全等三角形组成一个长方形，所以底8高5时面积是20。',{exact:true})).toBeHidden()
  await browser.setViewport({width:1440,height:1000})
  await openAs('teacher')
  await screen.getByRole('link','Memos 学习报告详情',{exact:true}).tap()
  await browser.reload()
  expect(await browser.evaluate(()=>new URL(location.href).searchParams.get('type'))).toBe('homework')
  await expect(screen.getByRole('dialog')).toBeHidden()
  await screen.getByLabel('按学生姓名检索').fill('Forum student')
  await expect(screen.getByText('新作业提交正文，仅点击学生后显示。',{exact:true})).toBeHidden()
  await expect(screen.getByText('证据不足 / 无法判断',{exact:true})).toBeVisible()
  await app.screenshot('issue146-homework-light-collapsed')
  await screen.getByRole('link','引用对话',{exact:true}).tap()
  await expect(screen.getByText('新作业提交正文，仅点击学生后显示。',{exact:true})).toBeVisible()
  await expect(screen.getByText('我用两个全等三角形拼成长方形，所以面积是底乘高的一半。',{exact:true})).toBeVisible()
  await screen.getByRole('button','收起作答',{exact:true}).tap()
  await expect(screen.getByLabel('按学生姓名检索')).toHaveValue('Forum student')

})
