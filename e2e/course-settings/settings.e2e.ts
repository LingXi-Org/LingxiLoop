import { test } from '@e2e-dev/web'
import { expect } from 'e2e'

test('learner cannot load or edit course settings', async ({ app, browser, screen }) => {
  await app.open('/e2e/course-settings/index.html?scenario=student')
  await expect(screen.getByText('你没有查看课程设置的权限。', { exact: true })).toBeVisible()
  await expect(browser.locator('#course-settings-name')).toHaveCount(0)
  await expect(screen.getByRole('button', '保存基本资料', { exact: true })).toHaveCount(0)
  expect(JSON.parse((await screen.getByLabel('课程设置请求证据').textContent())!)).toEqual({ reads: [], writes: [], refreshes: 0 })
})

test('fresh learner course details override stale teacher space edit capability', async ({ app, browser, screen }) => {
  await app.open('/e2e/course-settings/index.html?scenario=stale-role')
  await expect(browser.locator('#course-settings-name')).toHaveValue('合成物理课')
  await expect(browser.locator('#course-settings-name')).toBeDisabled()
  await expect(browser.locator('#course-settings-description')).toBeDisabled()
  await expect(screen.getByRole('button', '保存基本资料', { exact: true })).toHaveCount(0)
  const evidence = JSON.parse((await screen.getByLabel('课程设置请求证据').textContent())!)
  expect(evidence.reads).toEqual(['/api/courses/course-a'])
  expect(evidence.writes).toEqual([])
})

test('switching courses removes the old writable form while loading and after failure; retry saves the new course', async ({ app, browser, screen }) => {
  await app.open('/e2e/course-settings/index.html?scenario=switch')
  await expect(browser.locator('#course-settings-name')).toHaveValue('合成物理课')
  await screen.getByRole('button', '模拟切换课程', { exact: true }).tap()
  await expect(screen.getByLabel('课程设置请求证据')).toContainText('/api/courses/course-b')
  await expect(browser.locator('#course-settings-name')).toHaveCount(0)
  await screen.getByRole('button', '模拟加载失败', { exact: true }).tap()
  await expect(screen.getByRole('button', '重试', { exact: true })).toBeVisible()
  await expect(browser.locator('#course-settings-name')).toHaveCount(0)
  await screen.getByRole('button', '重试', { exact: true }).tap()
  await expect(browser.locator('#course-settings-name')).toHaveValue('合成化学课')
  await browser.locator('#course-settings-description').fill('只更新当前合成化学课程')
  await screen.getByRole('button', '保存基本资料', { exact: true }).tap()
  await screen.getByRole('button', '保存更改', { exact: true }).tap()
  await expect(screen.getByText('课程设置已保存', { exact: true })).toBeVisible()
  const evidence = JSON.parse((await screen.getByLabel('课程设置请求证据').textContent())!)
  expect(evidence.writes).toEqual([{ path: '/api/courses/course-b', body: { name: '合成化学课', description: '只更新当前合成化学课程' } }])
  expect(evidence.refreshes).toBe(1)
  await app.screenshot('course-settings-new-course-saved')
})

for (const target of ['revoke-write', 'switch-student']) test(`pending confirmation cannot send a stale course PATCH after ${target}`, async ({ app, browser, screen }) => {
  await app.open('/e2e/course-settings/index.html?scenario=confirmation')
  await expect(browser.locator('#course-settings-name')).toHaveValue('合成物理课')
  await screen.getByRole('button', '保存基本资料', { exact: true }).tap()
  await expect(screen.getByRole('alertdialog')).toBeVisible()
  await browser.evaluate((id) => { document.getElementById(id)!.click(); return null }, target)
  if (target === 'revoke-write') await expect(browser.locator('#course-settings-name')).toBeDisabled()
  else await expect(browser.locator('#course-settings-name')).toHaveCount(0)
  await screen.getByRole('button', '保存更改', { exact: true }).tap()
  await expect(screen.getByRole('alertdialog')).toHaveCount(0)
  const evidence = JSON.parse((await screen.getByLabel('课程设置请求证据').textContent())!)
  expect(evidence.writes).toEqual([])
  expect(evidence.refreshes).toBe(0)
  await expect(screen.getByText('课程设置已保存', { exact: true })).toHaveCount(0)
})
