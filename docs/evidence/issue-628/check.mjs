import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '/opt/codex/cua_node/lib/node_modules/playwright-core/index.mjs')
const base = process.env.SIDEBAR_BASE_URL || 'http://127.0.0.1:5180'
const out = process.env.SIDEBAR_OUTPUT || '/tmp/628-evidence'
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] })
const reports = []
const settle = page => page.waitForTimeout(260)
const state = page => page.locator('[data-slot=sidebar][data-side]')
const gap = page => page.locator('[data-slot=sidebar-gap]')
const width = locator => locator.evaluate(el => el.getBoundingClientRect().width)
async function noOverflow(page) { assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)) }
try {
  for (const viewportWidth of [1400, 768, 390, 320]) {
    const page = await browser.newPage({ viewport: { width: viewportWidth, height: 900 } })
    page.setDefaultTimeout(10000)
    console.log(`checking ${viewportWidth}`)
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route(`${base}/api/**`, route => route.fulfill({ json: { latestSeq: 0, entries: [], hasMore: false } }))
    await page.goto(`${base}/docs/evidence/issue-628/fixture.html`)
    const toggle = page.locator('[data-page-header] [data-slot=sidebar-trigger]:visible')
    await toggle.waitFor()
    if (viewportWidth >= 768) assert.equal(await width(gap(page)), 0)
    await toggle.focus(); await page.keyboard.press('Enter'); await settle(page)
    assert.equal(await toggle.getAttribute('aria-expanded'), 'true')
    // Synthetic content notification while the modal navigation owns user focus.
    await page.locator('button').filter({ hasText: '更新内容' }).evaluate(el => el.click()); await settle(page)
    assert.equal(await toggle.getAttribute('aria-expanded'), 'true')
    const left = await page.locator('[data-slot=sidebar-container], [data-mobile=true][data-sidebar=sidebar]').first().boundingBox()
    assert.ok(left.width <= viewportWidth)
    await page.screenshot({ path: `${out}/left-open-${viewportWidth}.png` })
    if (viewportWidth >= 768) {
      assert.equal(await width(gap(page)), 300)
      assert.equal(await state(page).getAttribute('data-state'), 'expanded')
      const resize = page.getByRole('button', { name: '调整演示文稿导航宽度' })
      await resize.focus(); await page.keyboard.press('ArrowRight'); await settle(page)
      assert.equal(Math.round(await width(gap(page))), 310)
      await page.getByRole('button', { name: '收起演示文稿导航', exact: true }).click()
      await page.waitForTimeout(60)
      const during = await width(gap(page))
      assert.ok(during > 0 && during < 310, `left native transition missing: ${during}`)
      await settle(page)
      assert.ok(await toggle.evaluate(el => document.activeElement === el))
      await toggle.click(); await settle(page)
      await page.locator('[data-slot=sidebar-container]').getByRole('textbox', { name: '搜索演示文稿' }).focus()
      await page.keyboard.press('Control+b'); await settle(page)
      assert.equal(await width(gap(page)), 0)
      assert.ok(await toggle.evaluate(el => document.activeElement === el), 'shortcut collapse must restore focus')
    } else {
      assert.equal(await page.getByRole('dialog').count(), 1)
      await page.keyboard.press('Escape'); await page.waitForTimeout(60)
      assert.equal(await page.locator('[data-mobile=true][data-sidebar=sidebar]').evaluate(el => getComputedStyle(el).animationName), 'exit')
      await settle(page)
      assert.ok(await toggle.evaluate(el => document.activeElement === el), 'mobile close must restore focus')
    }
    for (let i=0; i<4; i++) {
      await toggle.click(); await page.waitForTimeout(30)
      await page.getByRole('button', { name: '收起演示文稿导航', exact: true }).click(); await page.waitForTimeout(30)
    }
    await settle(page)
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false')
    await noOverflow(page)
    await page.getByRole('button', { name: '切换模块' }).click()
    await page.getByRole('button', { name: '切换模块' }).click()
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false')
    await page.reload(); await toggle.waitFor()
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false')
    console.log(`Slides editor ${viewportWidth}`)
    // Real Slides page + host frame, with slow synthetic chat and editor services.
    await page.getByRole('button', { name: /打开「合成演示文稿/ }).click()
    const slidesFrame = page.locator('iframe[title*=演示文稿]')
    await slidesFrame.waitFor()
    await page.frameLocator('iframe[title*=演示文稿]').getByRole('textbox').fill('演示文稿保留草稿')
    await slidesFrame.evaluate(el => { window.slides628 = el })
    await toggle.click(); await settle(page)
    await page.getByRole('button', { name: '收起演示文稿导航', exact: true }).click(); await settle(page)
    assert.ok(await slidesFrame.evaluate(el => el === window.slides628))
    await page.getByRole('button', { name: '返回演示文稿列表' }).click()
    await page.getByRole('button', { name: /打开「合成演示文稿/ }).click()
    await slidesFrame.waitFor()
    assert.ok(await slidesFrame.evaluate(el => el === window.slides628))
    assert.equal(await page.frameLocator('iframe[title*=演示文稿]').getByRole('textbox').inputValue(), '演示文稿保留草稿')
    await page.getByRole('button', { name: '切换模块' }).click()
    console.log(`Canvas ${viewportWidth}`)
    const canvasToggle = page.getByRole('button', { name: '切换画板' })
    await page.getByRole('textbox', { name: '消息', exact: true }).fill('对话草稿')
    await canvasToggle.click(); await settle(page)
    const canvasFrame = page.locator('iframe[title*=设计]')
    await canvasFrame.waitFor()
    await canvasFrame.evaluate(el => { window.canvas628 = el })
    await page.frameLocator('iframe[title*=设计]').getByRole('textbox').fill('画板未保存草稿')
    const openGap = await width(gap(page))
    const canvasRect = await page.locator('[data-slot=sidebar-container]').boundingBox()
    if (viewportWidth === 1400) assert.ok(Math.abs(canvasRect.width - openGap) <= 1, 'Canvas container and gap must agree')
    if (viewportWidth === 768) assert.equal(openGap, 0, 'narrow workspace uses an overlay, no empty gap')
    if (viewportWidth >= 768) {
      assert.equal(await page.getByRole('dialog').count(), 0)
      await page.getByRole('button', { name: '关闭设计' }).focus()
      await page.keyboard.press('Shift+Tab')
      assert.ok(await page.getByRole('button', { name: '发送', exact: true }).evaluate(el => document.activeElement === el), 'desktop sidebar must not loop Tab away from chat')
      const resize = page.getByRole('button', { name: '调整对话与画板宽度' })
      if (viewportWidth === 1400) {
        await resize.focus(); await page.keyboard.press('ArrowLeft'); await settle(page)
        assert.ok(await width(gap(page)) > openGap)
        const beforeDrag = await width(gap(page)), box = await resize.boundingBox()
        await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
        await page.mouse.down(); await page.mouse.move(box.x - 30, box.y + box.height / 2); await page.mouse.up(); await settle(page)
        assert.ok(await width(gap(page)) > beforeDrag + 20, 'pointer width adjustment')
      }
    }
    await page.screenshot({ path: `${out}/right-open-${viewportWidth}.png` })
    await page.getByRole('button', { name: '关闭设计' }).click()
    if (viewportWidth === 1400) {
      await page.waitForTimeout(60)
      const during = await width(gap(page))
      assert.ok(during > 0 && during < openGap + 50, `right native transition missing: ${during}`)
    }
    if (viewportWidth < 768) {
      await page.waitForTimeout(60)
      const closing = await page.locator('[data-slot=sidebar-container]').evaluate(el => ({ name: getComputedStyle(el).animationName, visibility: getComputedStyle(el).visibility }))
      assert.equal(closing.name, 'exit'); assert.equal(closing.visibility, 'visible')
    }
    await settle(page)
    assert.ok(await canvasToggle.evaluate(el => document.activeElement === el))
    assert.ok(await canvasFrame.evaluate(el => el === window.canvas628))
    await canvasToggle.click(); await settle(page)
    assert.equal(await page.frameLocator('iframe[title*=设计]').getByRole('textbox').inputValue(), '画板未保存草稿')
    await page.setViewportSize({ width: viewportWidth >= 768 ? 390 : 1400, height: 900 }); await settle(page)
    assert.ok(await canvasFrame.evaluate(el => el === window.canvas628), 'resize must retain iframe')
    assert.equal(await page.frameLocator('iframe[title*=设计]').getByRole('textbox').inputValue(), '画板未保存草稿')
    await page.setViewportSize({ width: viewportWidth, height: 900 }); await settle(page)
    await page.getByRole('button', { name: '关闭设计' }).click(); await settle(page)
    assert.equal(await page.getByRole('textbox', { name: '消息', exact: true }).inputValue(), '对话草稿')
    for (let i=0;i<4;i++) {
      await canvasToggle.click(); await page.waitForTimeout(30)
      // Narrow Canvas covers the opener; use its visible native close control.
      await page.getByRole('button', { name: '关闭设计' }).click(); await page.waitForTimeout(30)
    }
    await settle(page)
    assert.equal(await page.locator('[data-design-open]').getAttribute('data-design-open'), 'false')
    await noOverflow(page)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await canvasToggle.click(); await settle(page)
    const motion = await page.locator('[data-slot=sidebar-container]').evaluate(el => ({ duration: getComputedStyle(el).transitionDuration, animation: getComputedStyle(el).animationName }))
    assert.ok(motion.duration.split(',').every(value => Number.parseFloat(value) < 0.001))
    assert.equal(motion.animation, 'none')
    await page.getByRole('button', { name: '关闭设计' }).click(); await page.waitForTimeout(30)
    if (viewportWidth < 768) assert.equal(await page.locator('[data-slot=sidebar-container]').evaluate(el => getComputedStyle(el).visibility), 'hidden')
    assert.deepEqual(errors, [])
    reports.push({ viewportWidth, initialCollapsed: true, manualToggleSurvivesUpdates: true, nativeTransitions: true, slidesAndCanvasRetained: true, crossBreakpointCanvasRetained: true, keyboardAndFocus: true, noPageOverflow: true, reducedMotion: motion, errors })
    await page.close()
  }
  // A direct deck URL is collapsed from the first page render too.
  const page = await browser.newPage({viewport:{width:1400,height:900}})
  await page.goto(`${base}/docs/evidence/issue-628/fixture.html?deck=deck`)
  await page.locator('iframe').waitFor()
  assert.equal(await width(gap(page)), 0)
  await page.screenshot({ path: `${out}/direct-deck-collapsed.png` })
  await page.reload(); await page.locator('iframe').waitFor()
  assert.equal(await width(gap(page)), 0)
  reports.push({ directDeckAndRefreshCollapsed: true })
  await writeFile(`${out}/results.json`, JSON.stringify(reports, null, 2)+'\n')
  console.log(JSON.stringify(reports, null, 2))
} finally { await browser.close() }
