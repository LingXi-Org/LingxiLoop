import { test } from '@e2e-dev/web'

test('inspect actual public trace demos', { timeout: 180_000 },async ({ app,browser,screen }) => {
  await browser.setViewport({width:1440,height:1000})
  await app.open('https://agent-prism.evilmartians.io')
  await browser.evaluate(async () => { await new Promise(resolve=>setTimeout(resolve,1200));document.querySelector('input[placeholder="Search spans"]')?.scrollIntoView({block:'start'});return true })
  await app.screenshot('agentprism-light-expanded')
  await screen.getByRole('button','Collapse all',{exact:true}).tap()
  await app.screenshot('agentprism-light-collapsed')
  await browser.evaluate(() => { document.documentElement.classList.add('dark');return true })
  await app.screenshot('agentprism-dark-collapsed')
  await screen.getByRole('button','Expand all',{exact:true}).tap()
  await app.screenshot('agentprism-dark-expanded')
  await app.open('https://jaeger.demo.jaegertracing.io/trace/61534829fe04ee518d72e547063e236b')
  console.log('JAEGER',await browser.evaluate(async () => {await new Promise(resolve=>setTimeout(resolve,1200));return JSON.stringify({text:document.body.innerText.slice(0,5000),buttons:[...document.querySelectorAll('button')].map(b=>({text:b.textContent,label:b.getAttribute('aria-label'),title:b.title}))}) }))
  await app.screenshot('jaeger-light-expanded')
  await app.open('http://127.0.0.1:5195')
  await screen.getByRole('button','Toggle mini / expanded').isVisible()
  await app.screenshot('waterfall-light-expanded')
  await screen.getByRole('button','Toggle mini / expanded').tap()
  await app.screenshot('waterfall-light-mini')
  await browser.evaluate(() => {document.documentElement.classList.add('dark');document.documentElement.style.colorScheme='dark';document.body.style.background='#151515';return true})
  await app.screenshot('waterfall-dark-mini-no-native-theme')
  await screen.getByRole('button','Toggle mini / expanded').tap()
  await app.screenshot('waterfall-dark-expanded-no-native-theme')
})
