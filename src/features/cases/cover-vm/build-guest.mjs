// Rebuild only the trusted compatibility adapter as a source string. This does
// not evaluate the bundle or instantiate QuickJS; generated figures are absent.
import { build } from 'esbuild'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
const result = await build({ entryPoints: [fileURLToPath(new URL('./guest-entry.ts', import.meta.url))], bundle: true, write: false, platform: 'neutral', format: 'iife', target: 'es2022', minify: true })
await writeFile(new URL('./guest-source.ts', import.meta.url), '// Generated by build-guest.mjs from guest-entry.ts; data for QuickJS only.\nexport const COVER_GUEST_SOURCE = ' + JSON.stringify(result.outputFiles[0].text) + '\n')
