-- Every published/closed course activity was previously a forum assignment.
-- Preserve IDs and authors; reject ambiguous or colliding published records.
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM learning_activities a JOIN courses c ON c.project_id=a.project_id AND c.company_id=a.company_id
    LEFT JOIN users publisher ON publisher.id=a.published_by LEFT JOIN users creator ON creator.id=a.created_by
    WHERE a.status IN ('PUBLISHED','CLOSED') AND (COALESCE(publisher.id,creator.id) IS NULL
      OR EXISTS(SELECT 1 FROM course_forum_posts p WHERE p.id=a.id))) THEN
    RAISE EXCEPTION 'Assignment migration requires explicit author/ID mapping; no data has been changed';
  END IF;
END $$;
INSERT INTO course_forum_posts(id,company_id,project_id,author_user_id,kind,title,body,created_at,updated_at,due_at,status,legacy_record)
  SELECT a.id,a.company_id,a.project_id,COALESCE(publisher.id,creator.id),'assignment',a.title,a.instructions,
    COALESCE(a.published_at,a.created_at),a.updated_at,a.due_at,a.status,to_jsonb(a)
  FROM learning_activities a JOIN courses c ON c.project_id=a.project_id AND c.company_id=a.company_id
  LEFT JOIN users publisher ON publisher.id=a.published_by LEFT JOIN users creator ON creator.id=a.created_by
  WHERE COALESCE(publisher.id,creator.id) IS NOT NULL;

CREATE TABLE course_forum_submissions (
  id text PRIMARY KEY,
  company_id text NOT NULL,
  project_id text NOT NULL,
  assignment_id text NOT NULL,
  learner_id text NOT NULL REFERENCES users(id),
  answer text NOT NULL DEFAULT '',
  links jsonb NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(links)='array'),
  attachments jsonb NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(attachments)='array'),
  source text NOT NULL CHECK(source IN ('STUDENT_ORIGINAL','AGENT_RELAY','AGENT_GENERATED')),
  submitted_by_agent text,
  agent_work_id text,
  assistance text NOT NULL DEFAULT 'NONE' CHECK(assistance IN ('NONE','HINT','GUIDED')),
  late boolean NOT NULL DEFAULT FALSE,
  client_submission_id text,
  submitted_at timestamptz NOT NULL DEFAULT NOW(),
  submission_sequence bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
  legacy_record jsonb,
  UNIQUE(company_id,project_id,id),
  UNIQUE(company_id,project_id,assignment_id,learner_id,client_submission_id),
  FOREIGN KEY(company_id,project_id,assignment_id) REFERENCES course_forum_posts(company_id,project_id,id),
  CHECK ((source='STUDENT_ORIGINAL' AND submitted_by_agent IS NULL AND agent_work_id IS NULL)
    OR (source<>'STUDENT_ORIGINAL' AND submitted_by_agent IS NOT NULL AND agent_work_id IS NOT NULL)),
  CHECK(source<>'AGENT_GENERATED' OR assistance='GUIDED')
);
INSERT INTO course_forum_submissions(id,company_id,project_id,assignment_id,learner_id,answer,links,attachments,
  source,submitted_by_agent,agent_work_id,assistance,late,client_submission_id,submitted_at,submission_sequence,legacy_record)
SELECT a.id,a.company_id,a.project_id,a.activity_id,a.learner_id,COALESCE(e.data->>'answer',''),
  COALESCE(e.data->'links','[]'),COALESCE(e.data->'attachments','[]'),a.source,a.submitted_by_agent,a.agent_work_id,
  a.assistance,a.late,a.client_submission_id,a.submitted_at,a.submission_sequence,jsonb_build_object('attempt',to_jsonb(a),'evidence',to_jsonb(e))
FROM learning_attempts a JOIN course_forum_posts p ON p.company_id=a.company_id AND p.project_id=a.project_id AND p.id=a.activity_id
JOIN evidence_records e ON e.company_id=a.company_id AND e.project_id=a.project_id AND e.id=a.evidence_id;
DO $$ BEGIN
  IF (SELECT COUNT(*) FROM learning_attempts a JOIN course_forum_posts p ON p.company_id=a.company_id AND p.project_id=a.project_id AND p.id=a.activity_id)
     <> (SELECT COUNT(*) FROM course_forum_submissions) THEN
    RAISE EXCEPTION 'Submission migration count mismatch; restore missing evidence before retry';
  END IF;
END $$;
