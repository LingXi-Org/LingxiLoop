import { readFile, realpath } from 'node:fs/promises'
import { join } from 'node:path'
import type { Request, Response } from 'express'

/** Only the two public program routes use this release cache. Private grant
 * pages/project files never fall back to it, and it is mounted read-only. */
export async function retainedEditorAsset(kind: 'design' | 'slides', name: string, root = '/var/lib/lingxiloop/editor-assets'): Promise<string | null> {
  const publicName = kind === 'design' ? /^design-[a-f0-9]{64}\.(?:js|css|woff2)$/ : /^[A-Za-z0-9_-]+\.(?:js|css|woff2)$/
  if (!publicName.test(name)) return null
  const file = join(root, kind, name)
  return await realpath(file).catch(() => null) === file ? file : null
}

/** An editor's blocking script and stylesheet, preloaded chunks and the fonts
 * its first view uses (math fonts load only with math), on the shared asset URLs. */
export async function readEditorPreloads(root: string, kind: 'design' | 'slides', origin: string) {
  const html = await readFile(join(root, 'index.html'), 'utf8')
  const names = [...html.matchAll(/(?:src|href)="[^"]*\/artifact-editor\/(?:design|slides)-assets\/([\w-]+\.(?:js|css))"/g)].map(match => match[1])
  for (const sheet of names.filter(name => name.endsWith('.css'))) {
    const css = await readFile(join(root, 'assets', sheet), 'utf8')
    names.push(...[...css.matchAll(/url\(\.\/([\w-]+\.woff2)\)/g)].map(match => match[1]))
  }
  return [...new Set(names)].map(name => `${origin}/artifact-editor/${kind}-assets/${name}`)
}

/** The caller validates the original path. Sidecars are generated by our build.
 * Only the grant-free shared asset routes are `public`, so the edge can cache them. */
export async function sendEditorAsset(request: Request, response: Response, file: string, type: string, immutable: boolean, scope: 'private' | 'public' = 'private') {
  const candidates = request.headers['accept-encoding'] ? ['br', 'gzip', 'identity'] : ['identity']
  const offered = (request.headers['accept-encoding'] ?? '').toLowerCase().split(',').map(part => {
    const [name, ...parameters] = part.trim().split(';')
    const quality = parameters.map(value => /^\s*q\s*=\s*([\d.]+)\s*$/.exec(value)).find(Boolean)
    return { name, quality: quality ? Number(quality[1]) : 1 }
  })
  const quality = (name: string) => (offered.find(item => item.name === name) ?? offered.find(item => item.name === '*'))?.quality
  response.vary('Accept-Encoding')
  while (candidates.length) {
    let encoding = request.acceptsEncodings(...candidates)
    // Express respects q-values but breaks ties by header order. Browsers list
    // gzip first; prefer the smaller prebuilt Brotli representation at equal q.
    if (encoding === 'gzip' && candidates.includes('br') && request.acceptsEncodings('br')
      && quality('br') === quality('gzip')) encoding = 'br'
    if (!encoding) break
    const variant = encoding === 'identity' ? file : `${file}.${encoding === 'br' ? 'br' : 'gz'}`
    const real = await realpath(variant).catch(() => null)
    if (real !== variant) { candidates.splice(candidates.indexOf(encoding), 1); continue }
    const bytes = await readFile(variant)
    response.status(200).set({ 'Content-Type': type, 'Content-Length': String(bytes.length),
      'X-Content-Type-Options': 'nosniff',
      'Cache-Control': immutable ? `${scope}, max-age=31536000, immutable` : 'no-cache' })
    if (encoding !== 'identity') response.set('Content-Encoding', encoding)
    response.end(request.method === 'HEAD' ? undefined : bytes)
    return
  }
  response.status(406).set('Cache-Control', 'no-store').end()
}
